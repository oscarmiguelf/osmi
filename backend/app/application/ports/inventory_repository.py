from decimal import Decimal
from typing import Protocol
from uuid import UUID


class InventoryRepository(Protocol):
    def stock_product(self, product_id: UUID) -> dict | None: ...
    def stock(self, branch_id: UUID, filters: dict, limit: int, offset: int) -> tuple[list[dict], int]: ...
    def stock_in_my_branches(self, product_id: UUID, user_id: UUID) -> list[dict]: ...
    def kardex(self, product_id: UUID, branch_id: UUID, filters: dict, limit: int, offset: int) -> list[dict]: ...
    def movements(self, branch_id: UUID, filters: dict, limit: int, offset: int) -> list[dict]: ...
    def lock_stock(self, branch_id: UUID, product_id: UUID) -> Decimal: ...
    def add_adjustment(self, user_id: UUID, branch_id: UUID, product_id: UUID, quantity: Decimal,
                       notes: str, reference: str | None) -> dict: ...
    def low_stock(self, branch_id: UUID) -> list[dict]: ...
    def commit(self) -> None: ...
