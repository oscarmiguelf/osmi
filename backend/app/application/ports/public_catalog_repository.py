from typing import Protocol
from uuid import UUID


class PublicCatalogRepository(Protocol):
    def products(self, q: str, category_id: UUID | None, kind: str, limit: int, offset: int) -> list[dict]: ...
    def categories(self) -> list[dict]: ...
    def whatsapp_number(self) -> str: ...
    def image(self, product_id: UUID, image_id: UUID) -> dict | None: ...
