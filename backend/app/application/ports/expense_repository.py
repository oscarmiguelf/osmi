from datetime import datetime
from typing import Protocol
from uuid import UUID

from app.application.ports.outgoing_payment_repository import OutgoingPaymentRepository


class ExpenseRepository(OutgoingPaymentRepository, Protocol):
    def supplier_active(self, supplier_id: UUID) -> bool: ...
    def create(self, user_id: UUID, branch_id: UUID, data: dict) -> UUID: ...
    def update(self, user_id: UUID, expense_id: UUID, fields: dict) -> None: ...
    def get(self, expense_id: UUID) -> dict | None: ...
    def search(self, branch_id: UUID, filters: dict, limit: int, offset: int) -> list[dict]: ...
    def summary(self, branch_id: UUID, start: datetime | None, end: datetime | None) -> dict: ...
    def void(self, user_id: UUID, expense_id: UUID, reason: str | None) -> None: ...
    def commit(self) -> None: ...
