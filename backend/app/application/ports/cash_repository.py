from datetime import datetime
from decimal import Decimal
from typing import Protocol
from uuid import UUID


class CashRepository(Protocol):
    def has_permission(self, user_id: UUID, module: str, permission: str) -> bool: ...
    # registers
    def registers_status(self, branch_id: UUID) -> list[dict]: ...
    def get_register(self, register_id: UUID) -> dict | None: ...
    def create_register(self, user_id: UUID, branch_id: UUID, name: str) -> dict | None: ...
    def rename_register(self, user_id: UUID, register_id: UUID, name: str) -> dict | None: ...
    def delete_register(self, user_id: UUID, register_id: UUID) -> None: ...
    def restore_register(self, user_id: UUID, register_id: UUID) -> dict | None: ...
    def nonzero_balances(self, register_id: UUID) -> int: ...
    def register_history(self, register_id: UUID, limit: int, offset: int) -> list[dict]: ...
    # sessions
    def current_session(self, user_id: UUID) -> dict | None: ...
    def open_session(self, register_id: UUID) -> dict | None: ...
    def occupy(self, user_id: UUID, register_id: UUID) -> dict | None: ...
    def release(self, register_id: UUID, by: UUID) -> dict | None: ...
    # payment methods
    def payment_methods(self, include_disabled: bool) -> list[dict]: ...
    def payment_method(self, method_id: UUID) -> dict | None: ...
    def update_payment_method(self, user_id: UUID, method_id: UUID, fields: dict) -> dict | None: ...
    # money
    def balances(self, register_id: UUID) -> list[dict]: ...
    def lock_balances(self, register_id: UUID) -> dict[UUID, Decimal]: ...
    def add_movement(self, user_id: UUID, register_id: UUID, method_id: UUID, type_name: str,
                     amount: Decimal, notes: str | None) -> dict: ...
    def movements(self, register_id: UUID, filters: dict, limit: int, offset: int) -> list[dict]: ...
    def sales_totals(self, register_id: UUID, start: datetime, end: datetime) -> list[dict]: ...
    # cuts
    def cut_period_start(self, register_id: UUID) -> datetime: ...
    def create_cut(self, user_id: UUID, register_id: UUID, started_at: datetime, notes: str | None,
                   details: list[tuple[UUID, Decimal, Decimal]], withdrawn: Decimal = ..., withdrawal_reason: str | None = None) -> UUID | None: ...
    def cuts(self, register_id: UUID, limit: int, offset: int) -> list[dict]: ...
    def get_cut(self, cut_id: UUID) -> dict | None: ...
    def commit(self) -> None: ...
