from datetime import datetime
from decimal import Decimal
from typing import Protocol
from uuid import UUID


class SaleRepository(Protocol):
    def has_permission(self, user_id: UUID, module: str, permission: str) -> bool: ...
    def current_register(self, user_id: UUID, branch_id: UUID) -> dict | None: ...
    def products(self, product_ids: list[UUID]) -> dict[UUID, dict]: ...
    def kit_components(self, kit_ids: list[UUID]) -> list[dict]: ...
    def branch_stock(self, branch_id: UUID, product_ids: list[UUID]) -> dict[UUID, Decimal]: ...
    def promotion(self, promotion_id: UUID, product_id: UUID, branch_id: UUID) -> dict | None: ...
    def active_promotions(self, branch_id: UUID) -> list[dict]: ...
    def payment_methods(self, method_ids: list[UUID]) -> dict[UUID, dict]: ...
    def credit_method(self) -> dict | None: ...
    def customer_credit(self, customer_id: UUID) -> dict | None: ...
    def quote_for_sale(self, quote_id: UUID) -> dict | None: ...
    def sale_owner(self, sale_id: UUID) -> dict | None: ...
    def create(self, user_id: UUID, branch_id: UUID, register_id: UUID, sale_id: UUID, header: dict,
               lines: list[dict], payments: list[dict]) -> None: ...
    def deliver(self, user_id: UUID, sale_id: UUID, item_ids: list[UUID]) -> int: ...
    def add_abonos(self, user_id: UUID, register_id: UUID, abonos: list[dict]) -> None: ...
    def create_return(self, user_id: UUID, register_id: UUID, return_id: UUID, sale_id: UUID, refund_total: Decimal,
                      reason: str | None, items: list[dict], refunds: list[dict]) -> None: ...
    def lock_sale(self, sale_id: UUID) -> dict | None: ...
    def search(self, branch_id: UUID, filters: dict, limit: int, offset: int) -> list[dict]: ...
    def get(self, sale_id: UUID) -> dict | None: ...
    def id_by_folio(self, branch_id: UUID, folio: str) -> UUID | None: ...
    def returnable(self, sale_id: UUID) -> list[dict]: ...
    def refund_for(self, sale_item_id: UUID, quantity: Decimal) -> Decimal: ...
    def credit_pending(self, branch_id: UUID, customer_id: UUID | None = None, lock: bool = False) -> list[dict]: ...
    def pending_deliveries(self, branch_id: UUID) -> list[dict]: ...
    def item_states(self, sale_id: UUID, item_ids: list[UUID]) -> list[dict]: ...
    def returns(self, branch_id: UUID, filters: dict, limit: int, offset: int) -> list[dict]: ...
    def get_return(self, return_id: UUID) -> dict | None: ...
    def history(self, sale_id: UUID) -> dict: ...
    def report(self, branch_id: UUID, start: datetime, end: datetime) -> dict: ...
    def appointment_for_sale(self, appointment_id: UUID) -> dict | None: ...
    def price_list_for(self, customer_id: UUID) -> dict | None: ...
    def list_tiers(self, list_id: UUID, product_ids: list[UUID]) -> dict: ...
    def product_benefits(self, product_ids: list[UUID]) -> dict: ...
    def customer_exists(self, customer_id: UUID) -> bool: ...
    def appointment_of_quote(self, quote_id: UUID) -> UUID | None: ...
    def benefits_for_use(self, benefit_ids: list[UUID]) -> dict: ...
    def commit(self) -> None: ...
