from datetime import datetime
from typing import Protocol
from uuid import UUID


class AuthRepository(Protocol):
    def find_user_by_email(self, email: str) -> dict | None: ...
    def register_failure(self, user_id: UUID, max_attempts: int, lock_minutes: int) -> bool: ...
    def register_success(self, user_id: UUID) -> None: ...
    def recent_ip_failures(self, ip: str, minutes: int) -> int: ...
    def create_refresh_token(self, user_id: UUID, family_id: UUID, token_hash: str,
                             session_started_at: datetime | None, idle_days: int, max_days: int,
                             ip: str | None, user_agent: str | None) -> UUID: ...
    def lock_refresh_token(self, token_hash: str) -> dict | None: ...
    def revoke_token(self, token_id: UUID, reason: str, replaced_by: UUID | None = None) -> None: ...
    def revoke_family(self, family_id: UUID, reason: str) -> None: ...
    def audit(self, user_id: UUID | None, email: str, event: str,
              ip: str | None, user_agent: str | None) -> None: ...
    def login_payload(self, user_id: UUID) -> dict | None: ...
    def commit(self) -> None: ...
