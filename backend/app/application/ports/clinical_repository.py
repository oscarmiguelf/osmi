from typing import Protocol
from uuid import UUID


class ClinicalRepository(Protocol):
    def patient(self, customer_id: UUID) -> dict | None: ...
    def log_access(self, user_id: UUID, customer_id: UUID, action: str) -> None: ...
    def background(self, customer_id: UUID) -> dict: ...
    def save_background(self, user_id: UUID, customer_id: UUID, data: dict) -> None: ...
    def notes(self, customer_id: UUID) -> list[dict]: ...
    def note(self, note_id: UUID) -> dict | None: ...
    def create_note(self, user_id: UUID, branch_id: UUID, data: dict) -> UUID: ...
    def update_note(self, note_id: UUID, data: dict) -> None: ...
    def sign_note(self, user_id: UUID, note_id: UUID) -> None: ...
    def add_addendum(self, user_id: UUID, note_id: UUID, text: str) -> None: ...
    def add_prescription(self, user_id: UUID, note_id: UUID, customer_id: UUID, items: list[dict]) -> UUID: ...
    def prescription(self, prescription_id: UUID) -> dict | None: ...
    def prescriptions(self, customer_id: UUID) -> list[dict]: ...
    def add_file(self, user_id: UUID, customer_id: UUID, note_id: UUID | None, label: str, file_name: str, content_type: str, size: int) -> dict: ...
    def files(self, customer_id: UUID) -> list[dict]: ...
    def file(self, file_id: UUID) -> dict | None: ...
    def dental_chart(self, customer_id: UUID) -> list[dict]: ...
    def add_dental(self, user_id: UUID, customer_id: UUID, entries: list[dict]) -> None: ...
    def add_consent(self, user_id: UUID, customer_id: UUID, data: dict) -> None: ...
    def consents(self, customer_id: UUID) -> list[dict]: ...
    def access_log(self, customer_id: UUID, limit: int) -> list[dict]: ...
    def recent(self, user_id: UUID, branch_id: UUID) -> list[dict]: ...
    def appointment(self, appointment_id: UUID) -> dict | None: ...
    def setting(self, key: str) -> str: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
