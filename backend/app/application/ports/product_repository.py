from decimal import Decimal
from typing import Protocol
from uuid import UUID


class ProductRepository(Protocol):
    def has_permission(self, user_id: UUID, module: str, permission: str) -> bool: ...
    def ref_active(self, table: str, item_id: UUID) -> dict | None: ...
    def search(self, branch_id: UUID | None, filters: dict, limit: int, offset: int) -> tuple[list[dict], int]: ...
    def get(self, product_id: UUID, branch_id: UUID | None) -> dict | None: ...
    def by_barcode(self, barcode: str, branch_id: UUID | None) -> dict | None: ...
    def create(self, user_id: UUID, data: dict) -> UUID | None: ...
    def add_initial_stock(self, user_id: UUID, branch_id: UUID, product_id: UUID, quantity) -> None: ...
    def update(self, user_id: UUID, product_id: UUID, fields: dict) -> bool | None: ...
    def delete(self, user_id: UUID, product_id: UUID) -> None: ...
    def restore(self, user_id: UUID, product_id: UUID) -> bool: ...
    def has_history(self, product_id: UUID) -> bool: ...
    def delete_blockers(self, product_id: UUID) -> dict[str, int]: ...
    def history(self, product_id: UUID, limit: int, offset: int) -> list[dict]: ...
    def replace_suppliers(self, user_id: UUID, product_id: UUID, supplier_ids: list[UUID]) -> None: ...
    def replace_components(self, user_id: UUID, kit_id: UUID, components: dict[UUID, Decimal]) -> None: ...
    def commit(self) -> None: ...
