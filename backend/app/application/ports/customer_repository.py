from decimal import Decimal
from typing import Protocol
from uuid import UUID


class CustomerRepository(Protocol):
    def has_permission(self, user_id: UUID, module: str, permission: str) -> bool: ...
    def search(self, q: str, sort: str, limit: int, offset: int) -> tuple[list[dict], int]: ...
    def get(self, customer_id: UUID) -> dict | None: ...
    def count_same_phone(self, phone: str, exclude_id: UUID) -> int: ...
    def create(self, user_id: UUID, data: dict) -> dict: ...
    def update(self, user_id: UUID, customer_id: UUID, fields: dict) -> dict | None: ...
    def delete(self, user_id: UUID, customer_id: UUID) -> None: ...
    def restore(self, user_id: UUID, customer_id: UUID) -> dict | None: ...
    def balance(self, customer_id: UUID) -> Decimal: ...
    def history(self, customer_id: UUID, limit: int, offset: int) -> list[dict]: ...
    def credit_summary(self, customer_id: UUID) -> dict | None: ...
    def credit_movements(self, customer_id: UUID, limit: int, offset: int) -> list[dict]: ...
    def pending_sales(self, customer_id: UUID, limit: int, offset: int) -> list[dict]: ...
    def sales(self, customer_id: UUID, limit: int, offset: int) -> list[dict]: ...
    def price_list_active(self, list_id: UUID) -> bool: ...
    def commit(self) -> None: ...
