from decimal import Decimal
from typing import Literal, Protocol
from uuid import UUID

Kind = Literal["expense", "purchase"]


class OutgoingPaymentRepository(Protocol):
    """What an expense or a purchase was paid with: cash out of a register, another way, or still owed."""
    def my_register(self, user_id: UUID, branch_id: UUID) -> dict | None: ...
    def lock_cash(self, register_id: UUID) -> tuple[UUID, Decimal]: ...
    def add_payment(self, user_id: UUID, kind: Kind, parent_id: UUID, source: str, amount: Decimal,
                    register_id: UUID | None, method_id: UUID | None, notes: str | None) -> None: ...
    def payments(self, kind: Kind, parent_id: UUID) -> list[dict]: ...
    def return_cash(self, user_id: UUID, kind: Kind, parent_id: UUID) -> Decimal: ...
