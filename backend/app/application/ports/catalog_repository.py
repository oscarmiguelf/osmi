from __future__ import annotations  # `list` below is also a method name

from typing import Protocol
from uuid import UUID


class CatalogRepository(Protocol):
    def list(self, catalog: str, include_deleted: bool) -> list[dict]: ...
    def get(self, catalog: str, item_id: UUID) -> dict | None: ...
    def create(self, catalog: str, user_id: UUID, data: dict) -> dict | None: ...
    def update(self, catalog: str, user_id: UUID, item_id: UUID, fields: dict) -> dict | None: ...
    def delete(self, catalog: str, user_id: UUID, item_id: UUID) -> None: ...
    def restore(self, catalog: str, user_id: UUID, item_id: UUID) -> dict | None: ...
    def usage(self, catalog: str, item_id: UUID) -> int: ...
    def set_default_tax_rate(self, user_id: UUID, item_id: UUID) -> None: ...
    def existing_brands(self, ids: list[UUID]) -> set[UUID]: ...
    def merge_brands(self, user_id: UUID, from_ids: list[UUID], to_id: UUID) -> int: ...
    def commit(self) -> None: ...
