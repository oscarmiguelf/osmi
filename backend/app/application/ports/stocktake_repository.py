from typing import Protocol
from uuid import UUID


class StocktakeRepository(Protocol):
    def has_permission(self, user_id: UUID, module: str, permission: str) -> bool: ...
    def search(self, branch_id: UUID, filters: dict, limit: int, offset: int) -> list[dict]: ...
    def open_in_branch(self, branch_id: UUID) -> dict | None: ...
    def get(self, stocktake_id: UUID) -> dict | None: ...
    def totals(self, stocktake_id: UUID) -> dict: ...
    def uncounted_count(self, stocktake_id: UUID, branch_id: UUID) -> int: ...
    def create(self, user_id: UUID, branch_id: UUID, notes: str | None) -> UUID | None: ...
    def search_countable(self, q: str, limit: int) -> list[dict]: ...
    def countable_product(self, product_id: UUID | None, barcode: str | None) -> dict | None: ...
    def upsert_item(self, user_id: UUID, stocktake_id: UUID, product_id: UUID, counted, notes: str | None) -> dict: ...
    def delete_item(self, user_id: UUID, stocktake_id: UUID, product_id: UUID) -> bool: ...
    def items(self, stocktake_id: UUID, filters: dict, limit: int, offset: int) -> list[dict]: ...
    def uncounted(self, stocktake_id: UUID, branch_id: UUID, filters: dict, limit: int, offset: int) -> list[dict]: ...
    def set_status(self, user_id: UUID, stocktake_id: UUID, status: str) -> bool: ...
    def movements(self, stocktake_id: UUID) -> list[dict]: ...
    def history(self, stocktake_id: UUID, limit: int, offset: int) -> list[dict]: ...
    def sheet(self, stocktake_id: UUID, branch_id: UUID) -> list[dict]: ...
    def commit(self) -> None: ...
