from datetime import datetime
from decimal import Decimal
from typing import Protocol
from uuid import UUID

from app.application.ports.outgoing_payment_repository import OutgoingPaymentRepository


class PurchaseRepository(OutgoingPaymentRepository, Protocol):
    def supplier_active(self, supplier_id: UUID) -> bool: ...
    def stock_products(self, product_ids: list[UUID]) -> dict[UUID, dict]: ...
    def cost_basis(self, product_ids: list[UUID]) -> list[dict]: ...
    def set_cost(self, user_id: UUID, product_id: UUID, cost: Decimal) -> None: ...
    def create(self, user_id: UUID, branch_id: UUID, header: dict, items: list[dict]) -> UUID: ...
    def update(self, user_id: UUID, purchase_id: UUID, fields: dict) -> None: ...
    def search(self, branch_id: UUID, filters: dict, limit: int, offset: int) -> list[dict]: ...
    def get(self, purchase_id: UUID) -> dict | None: ...
    def items(self, purchase_id: UUID) -> list[dict]: ...
    def lock_branch_stock(self, branch_id: UUID, product_ids: list[UUID]) -> dict[UUID, Decimal]: ...
    def void(self, user_id: UUID, branch_id: UUID, purchase_id: UUID, quantities: dict[UUID, Decimal]) -> None: ...
    def history(self, purchase_id: UUID, limit: int, offset: int) -> list[dict]: ...
    def last_price(self, product_id: UUID) -> dict | None: ...
    def product_lines(self, branch_id: UUID, product_id: UUID, limit: int, offset: int) -> list[dict]: ...
    def summary(self, branch_id: UUID, start: datetime, end: datetime, tz: str) -> dict: ...
    def commit(self) -> None: ...
