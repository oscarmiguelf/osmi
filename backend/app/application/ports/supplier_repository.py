from datetime import datetime
from typing import Protocol
from uuid import UUID


class SupplierRepository(Protocol):
    def search(self, q: str, include_deleted: bool, sort: str, limit: int, offset: int) -> tuple[list[dict], int]: ...
    def options(self, include_deleted: bool) -> list[dict]: ...
    def get(self, supplier_id: UUID, user_id: UUID) -> dict | None: ...
    def same_name(self, name: str, exclude_id: UUID | None) -> list[dict]: ...
    def create(self, user_id: UUID, data: dict) -> dict: ...
    def update(self, user_id: UUID, supplier_id: UUID, fields: dict) -> dict | None: ...
    def delete(self, user_id: UUID, supplier_id: UUID) -> int: ...
    def restore(self, user_id: UUID, supplier_id: UUID) -> int: ...
    def history(self, supplier_id: UUID, limit: int, offset: int) -> list[dict]: ...
    def products(self, supplier_id: UUID, limit: int, offset: int) -> list[dict]: ...
    def missing_products(self, product_ids: list[UUID]) -> list[UUID]: ...
    def set_products(self, user_id: UUID, supplier_id: UUID, product_ids: list[UUID]) -> None: ...
    def link(self, user_id: UUID, supplier_id: UUID, product_id: UUID) -> bool: ...
    def unlink(self, user_id: UUID, supplier_id: UUID, product_id: UUID) -> bool: ...
    def purchases(self, user_id: UUID, supplier_id: UUID, start: datetime | None, end: datetime | None, limit: int, offset: int) -> list[dict]: ...
    def summary(self, user_id: UUID, supplier_id: UUID, start: datetime | None, end: datetime | None) -> dict: ...
    def price_history(self, user_id: UUID, supplier_id: UUID, product_id: UUID, limit: int) -> list[dict]: ...
    def commit(self) -> None: ...
