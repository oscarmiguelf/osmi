from datetime import datetime
from typing import Protocol
from uuid import UUID


class ReportRepository(Protocol):
    def spec(self, name: str) -> dict | None: ...
    def names(self) -> list[str]: ...
    def has_permission(self, user_id: UUID, module: str, permission: str) -> bool: ...
    def timezone(self, user_id: UUID) -> str: ...
    def user_branches(self, user_id: UUID, branch_ids: list[UUID]) -> set[UUID]: ...
    def run(self, name: str, params: dict, order: tuple[str, str] | None = None) -> tuple[list[dict], dict]: ...
    def record_export(self, user_id: UUID, report: str, fmt: str, parameters: dict, row_count: int) -> None: ...
    def dashboard(self, branches: list[UUID], days: list[tuple[datetime, datetime]], tz: str) -> dict: ...
    def security_events(self, hours: int) -> dict: ...
