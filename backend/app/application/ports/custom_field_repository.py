from typing import Protocol
from uuid import UUID


class CustomFieldRepository(Protocol):
    def active(self, entity: str) -> list[dict]: ...
    def get(self, field_id: UUID) -> dict | None: ...
    def create(self, user_id: UUID | None, data: dict) -> dict | None: ...
    def update(self, user_id: UUID, field_id: UUID, data: dict) -> dict | None: ...
    def delete(self, user_id: UUID, field_id: UUID) -> None: ...
    def commit(self) -> None: ...
