from typing import Protocol
from uuid import UUID


class BranchRepository(Protocol):
    def has_permission(self, user_id: UUID, module: str, permission: str) -> bool: ...
    def is_super_admin(self, user_id: UUID) -> bool: ...
    def list_all(self, include_deleted: bool) -> list[dict]: ...
    def get(self, branch_id: UUID) -> dict | None: ...
    def conflicts(self, name: str | None, code: str | None, exclude_id: UUID | None) -> list[str]: ...
    def code_editable(self, branch_id: UUID) -> bool: ...
    def create(self, user_id: UUID, data: dict) -> dict | None: ...
    def update(self, user_id: UUID, branch_id: UUID, fields: dict) -> dict | None: ...
    def delete(self, user_id: UUID, branch_id: UUID) -> None: ...
    def restore(self, user_id: UUID, branch_id: UUID) -> dict | None: ...
    def delete_blockers(self, branch_id: UUID) -> dict[str, int]: ...
    def history(self, branch_id: UUID, limit: int, offset: int) -> list[dict]: ...
    def members(self, branch_id: UUID) -> list[dict]: ...
    def user_exists(self, user_id: UUID) -> bool: ...
    def branches_of(self, user_id: UUID) -> list[dict]: ...
    def active_branch_ids(self, branch_ids: list[UUID]) -> set[UUID]: ...
    def open_work(self, user_id: UUID, branch_ids: list[UUID]) -> dict[str, int]: ...
    def assign(self, by: UUID, user_id: UUID, branch_ids: list[UUID]) -> int: ...
    def unassign(self, by: UUID, user_id: UUID, branch_ids: list[UUID]) -> int: ...
    def commit(self) -> None: ...
