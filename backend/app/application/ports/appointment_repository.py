from datetime import datetime
from typing import Protocol
from uuid import UUID


class AppointmentRepository(Protocol):
    def search(self, branch_id: UUID, filters: dict, limit: int) -> list[dict]: ...  # filters.only: just theirs
    def get(self, appointment_id: UUID) -> dict | None: ...
    def customer_active(self, customer_id: UUID) -> bool: ...
    def staff(self, branch_id: UUID) -> list[dict]: ...
    def clash(self, assigned_to: UUID, starts_at: datetime, ends_at: datetime, exclude: UUID | None) -> dict | None: ...
    def create(self, user_id: UUID, branch_id: UUID, data: dict) -> UUID: ...
    def update(self, user_id: UUID, appointment_id: UUID, fields: dict, reason: str | None = None) -> None: ...
    def add_note(self, user_id: UUID, appointment_id: UUID, note: str) -> None: ...
    def customer_appointments(self, user_id: UUID, customer_id: UUID, limit: int, offset: int, only: UUID | None = None) -> list[dict]: ...
    def service_products(self, ids: list[UUID]) -> list[dict]: ...
    def set_services(self, user_id: UUID, appointment_id: UUID, lines: list[dict]) -> None: ...
    def commit(self) -> None: ...
