from typing import Protocol
from uuid import UUID


class PromotionRepository(Protocol):
    def search(self, filters: dict, limit: int, offset: int) -> list[dict]: ...
    def get(self, promotion_id: UUID) -> dict | None: ...
    def missing_products(self, product_ids: list[UUID]) -> list[UUID]: ...
    def missing_branches(self, branch_ids: list[UUID]) -> list[UUID]: ...
    def create(self, user_id: UUID, data: dict) -> UUID: ...
    def update(self, user_id: UUID, promotion_id: UUID, fields: dict) -> None: ...
    def set_links(self, user_id: UUID, promotion_id: UUID, table: str, column: str, ids: list[UUID]) -> None: ...
    def delete(self, user_id: UUID, promotion_id: UUID) -> None: ...
    def restore(self, user_id: UUID, promotion_id: UUID) -> None: ...
    def history(self, promotion_id: UUID, limit: int, offset: int) -> list[dict]: ...
    def commit(self) -> None: ...
