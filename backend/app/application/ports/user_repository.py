from typing import Protocol
from uuid import UUID


class UserRepository(Protocol):
    def has_permission(self, user_id: UUID, module: str, permission: str) -> bool: ...
    def is_super_admin(self, user_id: UUID) -> bool: ...
    def permission_set(self, user_id: UUID) -> set[tuple[str, str]]: ...
    def other_user_admins(self, user_id: UUID) -> int: ...
    def timezone_exists(self, timezone: str) -> bool: ...
    def search(self, q: str, status: str | None, branch_id: UUID | None, limit: int, offset: int) -> tuple[list[dict], int]: ...
    def get(self, user_id: UUID) -> dict | None: ...
    def password_hash(self, user_id: UUID) -> str | None: ...
    def create(self, by: UUID, data: dict, password_hash: str) -> dict | None: ...
    def update(self, by: UUID, user_id: UUID, fields: dict) -> dict | None: ...
    def set_active(self, by: UUID, user_id: UUID, active: bool) -> None: ...
    def unlock(self, by: UUID, user_id: UUID) -> None: ...
    def set_password(self, by: UUID, user_id: UUID, password_hash: str, must_change: bool) -> None: ...
    def revoke_sessions(self, user_id: UUID, reason: str) -> int: ...
    def delete(self, by: UUID, user_id: UUID) -> None: ...
    def restore(self, by: UUID, user_id: UUID) -> dict | None: ...
    def sessions(self, user_id: UUID) -> list[dict]: ...
    def login_history(self, user_id: UUID, limit: int, offset: int) -> list[dict]: ...
    def history(self, user_id: UUID, limit: int, offset: int) -> list[dict]: ...
    def commit(self) -> None: ...
