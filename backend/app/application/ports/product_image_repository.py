from __future__ import annotations  # `list` below is also a method name

from typing import Protocol
from uuid import UUID


class ProductImageRepository(Protocol):
    def product_active(self, product_id: UUID) -> bool: ...
    def list(self, product_id: UUID) -> list[dict]: ...
    def get(self, product_id: UUID, image_id: UUID) -> dict | None: ...
    def add(self, user_id: UUID, product_id: UUID, file_name: str, content_type: str, size: int) -> dict: ...
    def delete(self, image_id: UUID) -> None: ...
    def set_order(self, product_id: UUID, image_ids: list[UUID]) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
