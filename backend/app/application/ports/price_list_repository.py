from typing import Protocol
from uuid import UUID


class PriceListRepository(Protocol):
    def all(self) -> list[dict]: ...
    def get(self, list_id: UUID) -> dict | None: ...
    def create(self, user_id: UUID, data: dict) -> dict | None: ...
    def update(self, user_id: UUID, list_id: UUID, data: dict) -> dict | None: ...
    def delete(self, user_id: UUID, list_id: UUID) -> None: ...
    def customers_using(self, list_id: UUID) -> int: ...
    def missing_products(self, product_ids: list[UUID]) -> list[UUID]: ...
    def set_items(self, user_id: UUID, list_id: UUID, items: list[dict]) -> None: ...
    def commit(self) -> None: ...
