from datetime import datetime
from typing import Protocol
from uuid import UUID


class CalendarRepository(Protocol):
    def access_level(self, user_id: UUID, calendar_id: UUID) -> str | None: ...
    def list_calendars(self, user_id: UUID) -> list[dict]: ...
    def create_calendar(self, user_id: UUID, data: dict) -> dict: ...
    def update_calendar(self, user_id: UUID, calendar_id: UUID, fields: dict) -> dict: ...
    def delete_calendar(self, user_id: UUID, calendar_id: UUID) -> None: ...
    def user_is_active(self, user_id: UUID) -> bool: ...
    def search_users(self, user_id: UUID, q: str) -> list[dict]: ...
    def list_members(self, calendar_id: UUID) -> list[dict]: ...
    def add_member(self, user_id: UUID, calendar_id: UUID, member_id: UUID, level: str) -> dict | None: ...
    def update_member(self, user_id: UUID, calendar_id: UUID, member_id: UUID, level: str) -> dict | None: ...
    def revoke_member(self, user_id: UUID, calendar_id: UUID, member_id: UUID) -> bool: ...
    def list_events(self, user_id: UUID, start: datetime, end: datetime,
                    calendar_ids: list[UUID] | None) -> list[dict]: ...
    def get_event(self, event_id: UUID) -> dict | None: ...
    def customer_is_active(self, customer_id: UUID) -> bool: ...
    def create_event(self, user_id: UUID, calendar_id: UUID, data: dict) -> dict: ...
    def update_event(self, user_id: UUID, event_id: UUID, fields: dict) -> dict: ...
    def delete_event(self, user_id: UUID, event_id: UUID) -> None: ...
    def audit(self, calendar_id: UUID, limit: int, offset: int) -> list[dict]: ...
    def set_timezone(self, user_id: UUID, timezone: str) -> bool: ...
    def commit(self) -> None: ...
