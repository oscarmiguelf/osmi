from typing import Protocol
from uuid import UUID


class AccessRepository(Protocol):
    def is_super_admin(self, user_id: UUID) -> bool: ...
    def list_modules(self, include_inactive: bool, include_deleted: bool,
                     module_id: UUID | None = None) -> list[dict]: ...
    def module_by_code(self, code: str) -> dict | None: ...
    def create_module(self, data: dict) -> dict | None: ...
    def create_crud_permissions(self, module_id: UUID) -> None: ...
    def update_module(self, module_id: UUID, fields: dict) -> dict | None: ...
    def delete_module(self, user_id: UUID, module_id: UUID) -> None: ...
    def restore_module(self, module_id: UUID) -> bool: ...
    def get_permission(self, permission_id: UUID) -> dict | None: ...
    def permission_by_code(self, module_id: UUID, code: str) -> dict | None: ...
    def create_permission(self, module_id: UUID, data: dict) -> dict | None: ...
    def update_permission(self, permission_id: UUID, fields: dict) -> dict | None: ...
    def delete_permission(self, user_id: UUID, permission_id: UUID) -> None: ...
    def restore_permission(self, permission_id: UUID) -> bool: ...
    def user_exists(self, user_id: UUID) -> bool: ...
    def user_access(self, user_id: UUID) -> list[dict]: ...
    def existing_modules(self, module_ids: list[UUID]) -> set[UUID]: ...
    def permission_modules(self, permission_ids: list[UUID]) -> dict[UUID, UUID]: ...
    def user_grants(self, user_id: UUID) -> tuple[set[UUID], set[UUID]]: ...
    def replace_grants(self, granted_by: UUID, user_id: UUID,
                       module_ids: list[UUID], permission_ids: list[UUID]) -> None: ...
    def users_admin_exists(self) -> bool: ...
    def commit(self) -> None: ...
