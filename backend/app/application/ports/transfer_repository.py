from decimal import Decimal
from typing import Protocol
from uuid import UUID


class TransferRepository(Protocol):
    def branch_active(self, branch_id: UUID) -> bool: ...
    def stock_products(self, product_ids: list[UUID]) -> dict[UUID, dict]: ...
    def lock_stock(self, branch_id: UUID, product_ids: list[UUID]) -> dict[UUID, Decimal]: ...
    def create(self, user_id: UUID, from_branch: UUID, to_branch: UUID, notes: str | None, items: list[dict]) -> UUID: ...
    def search(self, branch_id: UUID, filters: dict, limit: int, offset: int) -> list[dict]: ...
    def in_transit(self, branch_id: UUID) -> list[dict]: ...
    def get(self, transfer_id: UUID) -> dict | None: ...
    def set_status(self, transfer_id: UUID, user_id: UUID, status: str) -> bool: ...
    def available_products(self, branch_id: UUID, q: str, limit: int) -> list[dict]: ...
    def commit(self) -> None: ...
