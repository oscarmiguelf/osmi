from typing import Protocol
from uuid import UUID


class BenefitRepository(Protocol):
    def product_kind(self, product_id: UUID) -> dict | None: ...
    def price_list_active(self, list_id: UUID) -> bool: ...
    def set_benefit(self, user_id: UUID, product_id: UUID, data: dict) -> None: ...
    def clear_benefit(self, product_id: UUID) -> None: ...
    def customer_benefits(self, customer_id: UUID) -> list[dict]: ...
    def expiring(self, days: int) -> list[dict]: ...
    def commit(self) -> None: ...
