from typing import Protocol
from uuid import UUID


class OfflineRepository(Protocol):
    """What a register stores to keep selling without internet, and what didn't match when its sales came back."""
    def snapshot(self, branch_id: UUID) -> dict: ...
    def folio_owner(self, offline_folio: str) -> UUID | None: ...
    def issues(self, branch_id: UUID, resolved: bool) -> list[dict]: ...
    def issue(self, issue_id: UUID) -> dict | None: ...
    def resolve(self, user_id: UUID, issue_id: UUID, note: str | None) -> None: ...
    def commit(self) -> None: ...
