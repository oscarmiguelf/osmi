-- Credit still owed on a sale = credit charged - abonos - credit cancelled by returns
CREATE OR REPLACE FUNCTION fn_sale_credit_outstanding(p_sale_id UUID)
RETURNS NUMERIC AS $$
DECLARE
    v_charged  NUMERIC(12,2);
    v_paid     NUMERIC(12,2);
    v_returned NUMERIC(12,2);
BEGIN
    SELECT COALESCE(SUM(p.amount), 0) INTO v_charged
      FROM sale_payments p JOIN payment_methods m ON m.id = p.payment_method_id
     WHERE p.sale_id = p_sale_id AND p.kind = 'sale' AND m.is_credit;

    SELECT COALESCE(SUM(amount), 0) INTO v_paid
      FROM sale_payments WHERE sale_id = p_sale_id AND kind = 'credit_payment';

    SELECT COALESCE(SUM(r.amount), 0) INTO v_returned
      FROM sale_return_refunds r JOIN payment_methods m ON m.id = r.payment_method_id
     WHERE r.sale_id = p_sale_id AND m.is_credit;

    RETURN v_charged - v_paid - v_returned;
END;
$$ LANGUAGE plpgsql STABLE;

-- Validations before a payment is inserted
CREATE OR REPLACE FUNCTION fn_sale_payments_before_insert()
RETURNS TRIGGER AS $$
DECLARE
    v_sale        RECORD;
    v_is_credit   BOOLEAN;
    v_outstanding NUMERIC(12,2);
BEGIN
    SELECT s.id, s.branch_id, s.cash_register_id, s.customer_id, s.created_at, st.name AS status
      INTO v_sale
      FROM sales s JOIN sale_statuses st ON st.id = s.status_id
     WHERE s.id = NEW.sale_id AND s.deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Sale % does not exist or is deleted', NEW.sale_id;
    END IF;

    SELECT is_credit INTO v_is_credit
      FROM payment_methods
     WHERE id = NEW.payment_method_id AND deleted_at IS NULL AND is_enabled;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Payment method % is disabled or does not exist', NEW.payment_method_id;
    END IF;

    IF NOT fn_user_in_branch(NEW.created_by, v_sale.branch_id) THEN
        RAISE EXCEPTION 'User % does not belong to the branch of the sale', NEW.created_by;
    END IF;

    IF NEW.kind = 'sale' THEN
        -- created_at = NOW() = start of the transaction: the sale was created in this transaction
        IF v_sale.created_at <> NOW() THEN
            RAISE EXCEPTION 'Payments of a sale must be registered in the same transaction as the sale. Use kind credit_payment for abonos';
        END IF;

        NEW.cash_register_id := v_sale.cash_register_id;

        IF v_is_credit THEN
            IF v_sale.customer_id IS NULL THEN
                RAISE EXCEPTION 'A sale with a credit portion needs a customer';
            END IF;
            IF NEW.amount_tendered IS NOT NULL THEN
                RAISE EXCEPTION 'amount_tendered does not apply to credit';
            END IF;
        END IF;

    ELSE  -- credit_payment (abono)
        IF v_is_credit THEN
            RAISE EXCEPTION 'An abono must be paid with a real payment method, not with credit';
        END IF;
        IF v_sale.status = 'RETURNED' THEN
            RAISE EXCEPTION 'The sale is RETURNED, it cannot receive abonos';
        END IF;
        IF NEW.cash_register_id IS NULL THEN
            RAISE EXCEPTION 'An abono needs the cash register where the money is received';
        END IF;

        -- the user must occupy that register, and it must be a register of the sale's branch
        PERFORM 1
          FROM cash_registers r
          JOIN cash_register_sessions cs ON cs.cash_register_id = r.id
                                        AND cs.ended_at IS NULL
                                        AND cs.user_id = NEW.created_by
         WHERE r.id = NEW.cash_register_id
           AND r.branch_id = v_sale.branch_id
           AND r.deleted_at IS NULL;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'User % is not occupying a cash register of the branch of this sale', NEW.created_by;
        END IF;

        v_outstanding := fn_sale_credit_outstanding(NEW.sale_id);
        IF NEW.amount > v_outstanding THEN
            RAISE EXCEPTION 'The abono (%) is greater than the credit still owed on the sale (%)', NEW.amount, v_outstanding;
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_sale_payments_before_insert
    BEFORE INSERT ON sale_payments
    FOR EACH ROW EXECUTE FUNCTION fn_sale_payments_before_insert();

-- Effects of a payment: cash movement or customer debt, and PENDING -> PAID
CREATE OR REPLACE FUNCTION fn_sale_payments_after_insert()
RETURNS TRIGGER AS $$
DECLARE
    v_is_credit BOOLEAN;
    v_customer  UUID;
    v_status    TEXT;
    v_type      UUID;
BEGIN
    SELECT is_credit INTO v_is_credit FROM payment_methods WHERE id = NEW.payment_method_id;
    SELECT s.customer_id, st.name INTO v_customer, v_status
      FROM sales s JOIN sale_statuses st ON st.id = s.status_id WHERE s.id = NEW.sale_id;

    IF NOT v_is_credit THEN
        SELECT id INTO v_type FROM cash_movement_types WHERE name = 'Sale' AND deleted_at IS NULL;
        IF v_type IS NULL THEN
            RAISE EXCEPTION 'Cash movement type ''Sale'' does not exist';
        END IF;

        PERFORM set_config('app.sale_cash', 'on', TRUE);
        INSERT INTO cash_register_movements
            (cash_register_id, payment_method_id, movement_type_id, amount, sale_id, notes, created_by)
        VALUES
            (NEW.cash_register_id, NEW.payment_method_id, v_type, NEW.amount, NEW.sale_id,
             CASE NEW.kind WHEN 'sale' THEN 'Sale payment' ELSE 'Abono' END, NEW.created_by);
        PERFORM set_config('app.sale_cash', 'off', TRUE);

    ELSE
        PERFORM fn_customer_credit_move(v_customer, NEW.sale_id, 'charge', NEW.amount, NEW.created_by);
    END IF;

    IF NEW.kind = 'credit_payment' THEN
        PERFORM fn_customer_credit_move(v_customer, NEW.sale_id, 'payment', -NEW.amount, NEW.created_by);

        IF v_status = 'PENDING' AND fn_sale_credit_outstanding(NEW.sale_id) = 0 THEN
            PERFORM fn_set_sale_status(NEW.sale_id, 'PAID', NEW.created_by);
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_sale_payments_after_insert
    AFTER INSERT ON sale_payments
    FOR EACH ROW EXECUTE FUNCTION fn_sale_payments_after_insert();

-- ---------------------------------------------------------------------
-- Check deferred to COMMIT (header and payments can be inserted in any order):
--   * the 'sale' payments add up to sales.total
--   * with a credit portion: the sale has a customer and status PENDING
--   * without credit: status PAID
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_sale_check_payments()
RETURNS TRIGGER AS $$
DECLARE
    v_sale_id UUID;
    v_total   NUMERIC(12,2);
    v_cust    UUID;
    v_status  TEXT;
    v_sum     NUMERIC(12,2);
    v_credit  NUMERIC(12,2);
BEGIN
    v_sale_id := CASE TG_TABLE_NAME WHEN 'sales' THEN NEW.id ELSE (TO_JSONB(NEW) ->> 'sale_id')::UUID END;  -- NEW.sale_id would fail on the header table

    SELECT s.total, s.customer_id, st.name INTO v_total, v_cust, v_status
      FROM sales s JOIN sale_statuses st ON st.id = s.status_id WHERE s.id = v_sale_id;
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    SELECT COALESCE(SUM(p.amount), 0),
           COALESCE(SUM(p.amount) FILTER (WHERE m.is_credit), 0)
      INTO v_sum, v_credit
      FROM sale_payments p JOIN payment_methods m ON m.id = p.payment_method_id
     WHERE p.sale_id = v_sale_id AND p.kind = 'sale';

    IF v_sum <> v_total THEN
        RAISE EXCEPTION 'Sale %: payments (%) do not add up to the total (%)', v_sale_id, v_sum, v_total;
    END IF;

    IF v_credit > 0 AND v_cust IS NULL THEN
        RAISE EXCEPTION 'Sale %: a credit portion needs a customer', v_sale_id;
    END IF;
    IF v_credit > 0 AND v_status <> 'PENDING' THEN
        RAISE EXCEPTION 'Sale %: a sale with a credit portion must be PENDING', v_sale_id;
    END IF;
    IF v_credit = 0 AND v_status <> 'PAID' THEN
        RAISE EXCEPTION 'Sale %: a sale without credit must be PAID', v_sale_id;
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_sales_check_payments
    AFTER INSERT ON sales
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_sale_check_payments();

CREATE CONSTRAINT TRIGGER trg_sale_payments_check_payments
    AFTER INSERT ON sale_payments
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    WHEN (NEW.kind = 'sale')
    EXECUTE FUNCTION fn_sale_check_payments();

