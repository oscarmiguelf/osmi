-- ---------------------------------------------------------------------
-- View: what is still returnable in each sale item
-- ---------------------------------------------------------------------
CREATE VIEW sale_items_returnable AS
SELECT i.id AS sale_item_id, i.sale_id, i.product_id, i.quantity AS sold_quantity,
       COALESCE(r.returned, 0)                AS returned_quantity,
       i.quantity - COALESCE(r.returned, 0)   AS returnable_quantity
FROM sale_items i
LEFT JOIN (SELECT sale_item_id, SUM(quantity) AS returned
             FROM sale_return_items GROUP BY sale_item_id) r ON r.sale_item_id = i.id;


