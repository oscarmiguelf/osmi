-- created and you can fix the error and run it again.
--
-- Contents, in order:
--   auth, calendar, branches, customers, products, inventory, cash, sales,
--   payments (+ customer credit), returns, transfers, quotes, taxes, promotions,
--   stocktakes (physical count), purchases
--   +  INITIAL DATA (last section)
--
-- INITIAL DATA created at the end:
--   * user  admin / password  admin      <-- CHANGE IT BEFORE ANY REAL USE
--   * test branch (code SUC1) + admin assigned to it
--   * product types: Product, Service, Kit  (Service: no stock; Kit: sells its components)
--   * one cash register in the test branch
--   * extra modules (customers, products, inventory, purchases, cash, calendar,
--     branches, transfers, quotes, promotions, stocktakes) with CRUD permissions, all granted to admin
--
-- The admin login field is the "email" column, so you log in with: admin
-- The password is stored as a bcrypt hash (cost 12) generated by pgcrypto.
-- =====================================================================

