    cash_register_id  UUID          NOT NULL REFERENCES cash_registers (id),   -- set by trigger for kind 'sale'
    amount            NUMERIC(12,2) NOT NULL,                                  -- applied to the sale / credit
    amount_tendered   NUMERIC(12,2),                                           -- what the customer handed over
    change_given      NUMERIC(12,2) GENERATED ALWAYS AS (
                          CASE WHEN amount_tendered IS NULL THEN NULL ELSE amount_tendered - amount END) STORED,
    reference         VARCHAR(100),                                            -- terminal / transfer reference

    created_by        UUID          NOT NULL REFERENCES users (id),
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_sale_payments_kind     CHECK (kind IN ('sale', 'credit_payment')),
    CONSTRAINT chk_sale_payments_amount   CHECK (amount > 0),
    CONSTRAINT chk_sale_payments_tendered CHECK (amount_tendered IS NULL OR amount_tendered >= amount)
);

