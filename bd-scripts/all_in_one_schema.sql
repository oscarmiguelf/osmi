-- =====================================================================
-- Promotions module: percent / amount / buy-X-get-Y offers per product and branch
-- Target: PostgreSQL 13+
-- Depends on: auth, branches, products, sales (and the earlier modules)
--
-- How it works:
--   * A promotion has a kind:
--       PERCENT      percent % off the line            (e.g. 15 % off)
--       AMOUNT       a fixed amount off PER UNIT       (e.g. $5 off each)
--       BUY_X_GET_Y  buy_quantity paid + get_quantity free, repeated  (2x1 = buy 1 get 1,
--                    3x2 = buy 2 get 1)
--   * It has a validity window (starts_at / ends_at), can be switched off (is_enabled),
--     applies to the products listed in promotion_products and, if promotion_branches
--     has rows, only to those branches (no rows = every branch).
--   * The POS asks fn_active_promotions(branch) for what is on offer. When it applies one
--     it sends sale_items.promotion_id; the database CALCULATES the discount of the line
--     (an informed discount other than the calculated one is rejected) and keeps the link,
--     so you can report how much each promotion gave away.
--   * Changing or ending a promotion never changes past sales (the discount is stored).
--   * A sale item without promotion_id can still carry a manual discount, as before.
--     One promotion per line; combining promotions is not supported.
-- =====================================================================


-- ---------------------------------------------------------------------
-- promotions
-- ---------------------------------------------------------------------
CREATE TABLE promotions (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name         VARCHAR(150)  NOT NULL,
    description  VARCHAR(500),
    kind         VARCHAR(15)   NOT NULL,
    percent      NUMERIC(5,2),                            -- PERCENT: 0 < percent <= 100
    amount       NUMERIC(12,2),                           -- AMOUNT: money off per unit
    buy_quantity INTEGER,                                 -- BUY_X_GET_Y: units paid
    get_quantity INTEGER,                                 -- BUY_X_GET_Y: units free
    starts_at    TIMESTAMPTZ   NOT NULL,
    ends_at      TIMESTAMPTZ   NOT NULL,
    is_enabled   BOOLEAN       NOT NULL DEFAULT TRUE,

    created_by   UUID          NOT NULL REFERENCES users (id),
    updated_by   UUID          NOT NULL REFERENCES users (id),
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    deleted_at   TIMESTAMPTZ,
    deleted_by   UUID          REFERENCES users (id),

    CONSTRAINT chk_promotions_name    CHECK (BTRIM(name) <> ''),
    CONSTRAINT chk_promotions_window  CHECK (ends_at > starts_at),
    CONSTRAINT chk_promotions_deleted CHECK ((deleted_at IS NULL) = (deleted_by IS NULL)),
    CONSTRAINT chk_promotions_kind    CHECK (
        (kind = 'PERCENT'     AND percent > 0 AND percent <= 100
                              AND amount IS NULL AND buy_quantity IS NULL AND get_quantity IS NULL)
     OR (kind = 'AMOUNT'      AND amount > 0
                              AND percent IS NULL AND buy_quantity IS NULL AND get_quantity IS NULL)
     OR (kind = 'BUY_X_GET_Y' AND buy_quantity >= 1 AND get_quantity >= 1
                              AND percent IS NULL AND amount IS NULL))
);

