-- =====================================================================
-- Transfers module: move stock between branches (IN_TRANSIT -> RECEIVED / CANCELLED)
-- Target: PostgreSQL 13+
-- Depends on:
--   auth_schema.sql      -> users, set_updated_at(), prevent_hard_delete()
--   branches_schema.sql  -> branches, fn_user_in_branch(), fn_next_folio()
--   products_schema.sql  -> products, product_types
--   inventory_schema.sql -> inventory_movements, inventory_movement_types, prevent_modification()
--
-- How it works:
--   * A transfer is created in the ORIGIN branch with its items, in one transaction.
--     Stock leaves the origin AT THAT MOMENT ('Transfer Out' movements): while the goods
--     travel they are in neither branch, and the transfer is IN_TRANSIT.
--   * The DESTINATION branch receives it: IN_TRANSIT -> RECEIVED. Stock enters the
--     destination ('Transfer In' movements). Everything must be received as sent;
--     a difference is corrected afterwards with an inventory Adjustment.
--   * The ORIGIN can cancel while it is IN_TRANSIT: CANCELLED, and the stock goes back
--     to the origin.
--   * Only products that track stock can be transferred (not services, not kits:
--     transfer their components).
--   * Items are append-only; the status is the only thing that changes, and every
--     change is recorded with who and when.
--   * The transfer folio looks like SUC1-T000003 (counter of the origin branch).
-- =====================================================================


