-- #####################################################################
-- FILE: payments_schema.sql
-- #####################################################################
-- =====================================================================
-- Payments module: sale payments (mixed methods, cash received / change,
-- card reference) and customer credit (limit, balance, abonos)
-- Target: PostgreSQL 13+
-- Depends on:
--   auth_schema.sql      -> users, prevent_hard_delete()
--   branches_schema.sql  -> fn_user_in_branch()
--   customers_schema.sql -> customers (credit_limit)
--   inventory_schema.sql -> prevent_modification()
--   cash_schema.sql      -> payment_methods (is_credit), cash registers / sessions / movements
--   sales_schema.sql     -> sales, sale_statuses, fn_set_sale_status(), fn_sales_audit()
--
-- How it works:
--   * A sale is paid with one or MANY payment rows (kind = 'sale'), registered in the
--     same transaction as the sale. They must add up to sales.total.
--   * The 'Credit' method (is_credit = TRUE) means "on the customer's account": it needs a
--     customer, never moves money in a register, and increases the customer's debt.
--   * Any other method moves money in the sale's register automatically
--     (one 'Sale' cash movement per payment, for the amount applied to the sale).
--   * amount_tendered = what the customer handed over; change_given = tendered - amount.
--   * A sale with a credit portion starts as PENDING, a fully paid one as PAID.
--   * Abonos (kind = 'credit_payment') are registered later at a register occupied by the
--     user, in the sale's branch. When the credit of a sale reaches 0 it becomes PAID.
--   * The customer's debt can never exceed customers.credit_limit.
--   * Payments are append-only. Credit refunds of returns live in returns_schema.sql.
-- =====================================================================


-- ---------------------------------------------------------------------
-- customer_credit_balances (current debt per customer)
--   Maintained ONLY through customer_credit_movements.
-- ---------------------------------------------------------------------
CREATE TABLE customer_credit_balances (
    customer_id UUID          PRIMARY KEY REFERENCES customers (id),
    balance     NUMERIC(12,2) NOT NULL DEFAULT 0,        -- what the customer owes
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_customer_credit_balances CHECK (balance >= 0)
);

CREATE TRIGGER trg_customer_credit_balances_no_delete
    BEFORE DELETE ON customer_credit_balances
    FOR EACH ROW EXECUTE FUNCTION prevent_modification();

CREATE OR REPLACE FUNCTION fn_customer_credit_balances_guard()
RETURNS TRIGGER AS $$
BEGIN
    IF COALESCE(current_setting('app.customer_credit', TRUE), 'off') = 'on' THEN
        RETURN NEW;
    END IF;

    IF TG_OP = 'INSERT' AND NEW.balance <> 0 THEN
