    INSERT INTO customer_credit_movements (customer_id, sale_id, movement_type, amount, created_by)
    VALUES (p_customer_id, p_sale_id, p_type, p_amount, p_user_id);
    PERFORM set_config('app.customer_credit', 'off', TRUE);
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------
-- sale_payments (append-only)
--   kind = 'sale'           payment of the sale itself (same transaction as the sale)
--   kind = 'credit_payment' abono to a sale's credit, made later at a register
