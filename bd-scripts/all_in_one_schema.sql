-- ---------------------------------------------------------------------
-- stocktakes: validations on UPDATE
--   * only status, notes and updated_by can be sent; closed_at / closed_by are filled here
--   * OPEN -> COMPLETED (needs at least one counted item) | OPEN -> CANCELLED
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_stocktakes_before_update()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.folio      IS DISTINCT FROM OLD.folio
    OR NEW.branch_id  IS DISTINCT FROM OLD.branch_id
    OR NEW.created_by IS DISTINCT FROM OLD.created_by
    OR NEW.closed_at  IS DISTINCT FROM OLD.closed_at
    OR NEW.closed_by  IS DISTINCT FROM OLD.closed_by THEN
        RAISE EXCEPTION 'Folio, branch, creator and closing data of a stocktake cannot be set by hand';
    END IF;

    IF OLD.status <> 'OPEN' THEN
        RAISE EXCEPTION 'A % stocktake cannot be modified', OLD.status;
    END IF;

    IF NEW.status <> OLD.status THEN
        IF NEW.status NOT IN ('COMPLETED', 'CANCELLED') THEN
            RAISE EXCEPTION 'Invalid stocktake status change: % -> %', OLD.status, NEW.status;
        END IF;

        IF NOT fn_user_in_branch(NEW.updated_by, NEW.branch_id) THEN
            RAISE EXCEPTION 'User % does not belong to the branch of the stocktake', NEW.updated_by;
        END IF;

        IF NEW.status = 'COMPLETED' THEN
            PERFORM 1 FROM stocktake_items WHERE stocktake_id = NEW.id AND deleted_at IS NULL;
            IF NOT FOUND THEN
                RAISE EXCEPTION 'Cannot complete a stocktake without counted items';
            END IF;
        END IF;

        NEW.closed_at := NOW();
        NEW.closed_by := NEW.updated_by;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_stocktakes_before_update
    BEFORE UPDATE ON stocktakes FOR EACH ROW EXECUTE FUNCTION fn_stocktakes_before_update();

-- ---------------------------------------------------------------------
-- stocktake_items: validations
--   INSERT: stocktake OPEN, counter belongs to the branch, product tracks stock,
--           system_quantity = the branch's stock right now
--   UPDATE: while OPEN only counted_quantity, notes and soft delete (a new count refreshes
--           system_quantity); the completion trigger may also set applied_adjustment
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_stocktake_items_before_insert()
RETURNS TRIGGER AS $$
DECLARE
    v_st RECORD;
BEGIN
    SELECT branch_id, status INTO v_st FROM stocktakes WHERE id = NEW.stocktake_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Stocktake % does not exist', NEW.stocktake_id;
    END IF;
    IF v_st.status <> 'OPEN' THEN
        RAISE EXCEPTION 'The stocktake is %, items can only be added while it is OPEN', v_st.status;
    END IF;

    IF NOT fn_user_in_branch(NEW.created_by, v_st.branch_id) THEN
        RAISE EXCEPTION 'User % does not belong to the branch of the stocktake', NEW.created_by;
    END IF;

    PERFORM 1
      FROM products p JOIN product_types t ON t.id = p.product_type_id
     WHERE p.id = NEW.product_id AND p.deleted_at IS NULL AND t.tracks_stock AND NOT t.is_kit;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Product % cannot be counted: it must be an active product that tracks stock (not a service or a kit)', NEW.product_id;
    END IF;

    SELECT COALESCE((SELECT current_stock FROM product_stock
                      WHERE product_id = NEW.product_id AND branch_id = v_st.branch_id AND deleted_at IS NULL), 0)
      INTO NEW.system_quantity;

    NEW.updated_by          := COALESCE(NEW.updated_by, NEW.created_by);
    NEW.applied_adjustment  := NULL;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_stocktake_items_before_insert
    BEFORE INSERT ON stocktake_items FOR EACH ROW EXECUTE FUNCTION fn_stocktake_items_before_insert();

CREATE OR REPLACE FUNCTION fn_stocktake_items_before_update()
RETURNS TRIGGER AS $$
DECLARE
    v_st RECORD;
BEGIN
    IF NEW.stocktake_id IS DISTINCT FROM OLD.stocktake_id
    OR NEW.product_id   IS DISTINCT FROM OLD.product_id
    OR NEW.created_by   IS DISTINCT FROM OLD.created_by THEN
        RAISE EXCEPTION 'Stocktake and product of an item cannot be changed';
    END IF;

    -- completion trigger: it may only set the applied adjustment
    IF COALESCE(current_setting('app.stocktake_complete', TRUE), 'off') = 'on' THEN
        RETURN NEW;
    END IF;

    IF NEW.applied_adjustment IS DISTINCT FROM OLD.applied_adjustment
    OR NEW.system_quantity    IS DISTINCT FROM OLD.system_quantity THEN
        RAISE EXCEPTION 'system_quantity and applied_adjustment are managed by the database';
    END IF;

    SELECT branch_id, status INTO v_st FROM stocktakes WHERE id = OLD.stocktake_id;
    IF v_st.status <> 'OPEN' THEN
        RAISE EXCEPTION 'The stocktake is %, its items cannot be modified', v_st.status;
    END IF;

    IF NOT fn_user_in_branch(NEW.updated_by, v_st.branch_id) THEN
        RAISE EXCEPTION 'User % does not belong to the branch of the stocktake', NEW.updated_by;
    END IF;

    IF NEW.counted_quantity IS DISTINCT FROM OLD.counted_quantity THEN
        SELECT COALESCE((SELECT current_stock FROM product_stock
                          WHERE product_id = NEW.product_id AND branch_id = v_st.branch_id AND deleted_at IS NULL), 0)
          INTO NEW.system_quantity;                      -- a new count looks at today's stock
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_stocktake_items_before_update
    BEFORE UPDATE ON stocktake_items FOR EACH ROW EXECUTE FUNCTION fn_stocktake_items_before_update();

-- ---------------------------------------------------------------------
-- Completion: leave the stock equal to what was counted
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_stocktakes_complete()
RETURNS TRIGGER AS $$
DECLARE
    v_type    UUID;
    v_item    RECORD;
    v_current NUMERIC(14,3);
    v_adjust  NUMERIC(14,3);
BEGIN
    SELECT id INTO v_type FROM inventory_movement_types WHERE name = 'Adjustment' AND deleted_at IS NULL;
    IF v_type IS NULL THEN
        RAISE EXCEPTION 'Inventory movement type ''Adjustment'' does not exist';
    END IF;

    FOR v_item IN
        SELECT id, product_id, counted_quantity
          FROM stocktake_items
         WHERE stocktake_id = NEW.id AND deleted_at IS NULL
         ORDER BY product_id
    LOOP
        SELECT COALESCE((SELECT current_stock FROM product_stock
                          WHERE product_id = v_item.product_id AND branch_id = NEW.branch_id AND deleted_at IS NULL), 0)
          INTO v_current;
        v_adjust := v_item.counted_quantity - v_current;

        IF v_adjust <> 0 THEN
            PERFORM set_config('app.stocktake_stock', 'on', TRUE);
            INSERT INTO inventory_movements
                (branch_id, product_id, movement_type_id, quantity, stocktake_id, reference, notes, created_by)
            VALUES (NEW.branch_id, v_item.product_id, v_type, v_adjust, NEW.id, NEW.folio,
                    'Stocktake ' || NEW.folio, NEW.closed_by);
            PERFORM set_config('app.stocktake_stock', 'off', TRUE);
        END IF;

        PERFORM set_config('app.stocktake_complete', 'on', TRUE);
        UPDATE stocktake_items
           SET applied_adjustment = v_adjust, updated_by = NEW.closed_by
         WHERE id = v_item.id;
        PERFORM set_config('app.stocktake_complete', 'off', TRUE);
    END LOOP;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_stocktakes_complete
    AFTER UPDATE OF status ON stocktakes
    FOR EACH ROW
    WHEN (OLD.status = 'OPEN' AND NEW.status = 'COMPLETED')
    EXECUTE FUNCTION fn_stocktakes_complete();

