-- View: how much each promotion has been used (excluding deleted and returned sales)
-- ---------------------------------------------------------------------
CREATE VIEW promotion_usage AS
SELECT p.id AS promotion_id, p.name, p.kind,
       COUNT(i.id)                  AS lines_sold,
       COALESCE(SUM(i.quantity), 0) AS units_sold,
       COALESCE(SUM(i.discount), 0) AS discount_given
FROM promotions p
LEFT JOIN sale_items i ON i.promotion_id = p.id
                      AND EXISTS (SELECT 1 FROM sales s
                                    JOIN sale_statuses st ON st.id = s.status_id
                                   WHERE s.id = i.sale_id AND s.deleted_at IS NULL AND st.name <> 'RETURNED')
WHERE p.deleted_at IS NULL
GROUP BY p.id, p.name, p.kind;

