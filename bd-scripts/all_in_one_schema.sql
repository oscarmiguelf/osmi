-- =====================================================================
-- Quotes module: quotes (cotizaciones) that can be converted into a sale
-- Target: PostgreSQL 13+
-- Depends on:
--   auth_schema.sql      -> users, set_updated_at(), prevent_hard_delete()
--   branches_schema.sql  -> branches, fn_user_in_branch(), fn_next_folio()
--   customers_schema.sql -> customers
--   products_schema.sql  -> products
--   inventory_schema.sql -> prevent_modification()
--   sales_schema.sql     -> sales
--
-- How it works:
--   * A quote belongs to ONE branch, has a folio (SUC1-Q000007) and a validity date.
--     The customer is optional (a walk-in prospect can have a quote); customer_name is
--     free text for that case.
--   * A quote does NOT move stock or money.
--   * A quote can't be edited. To change it, cancel it and create a new one.
--     Only its status changes: OPEN -> CANCELLED, or OPEN -> CONVERTED.
--   * Converting: the sale is created with sales.quote_id = the quote. The database
--     checks the quote is OPEN, not expired, from the same branch (and the same customer
--     if the quote has one), and marks it CONVERTED. The sale's items and prices are
--     entered normally, so they can differ from the quote.
--   * An OPEN quote past valid_until counts as expired (see quotes_open view); it is
--     simply not convertible any more.
-- =====================================================================


