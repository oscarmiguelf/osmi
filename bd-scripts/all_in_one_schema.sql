-- ---------------------------------------------------------------------
-- quotes: validations on UPDATE (only the status can change)
--   OPEN -> CANCELLED  by a user of the quote's branch
--   OPEN -> CONVERTED  only through a sale created from the quote
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_quotes_before_update()
RETURNS TRIGGER AS $$
DECLARE
    v_old TEXT;
    v_new TEXT;
BEGIN
    IF (TO_JSONB(NEW) - 'status_id' - 'updated_by' - 'updated_at')
       <> (TO_JSONB(OLD) - 'status_id' - 'updated_by' - 'updated_at') THEN
        RAISE EXCEPTION 'A quote cannot be edited. Cancel it and create a new one';
    END IF;

    IF NEW.status_id IS DISTINCT FROM OLD.status_id THEN
        SELECT name INTO v_old FROM quote_statuses WHERE id = OLD.status_id;
        SELECT name INTO v_new FROM quote_statuses WHERE id = NEW.status_id AND deleted_at IS NULL;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Quote status % does not exist or is deleted', NEW.status_id;
        END IF;

        IF v_old <> 'OPEN' OR v_new NOT IN ('CANCELLED', 'CONVERTED') THEN
            RAISE EXCEPTION 'Invalid quote status change: % -> %', v_old, v_new;
        END IF;

        IF v_new = 'CONVERTED'
           AND COALESCE(current_setting('app.quote_convert', TRUE), 'off') <> 'on' THEN
            RAISE EXCEPTION 'A quote is converted by creating a sale with that quote_id';
        END IF;

        IF v_new = 'CANCELLED' AND NOT fn_user_in_branch(NEW.updated_by, NEW.branch_id) THEN
            RAISE EXCEPTION 'Only a user of the quote''s branch can cancel it';
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

