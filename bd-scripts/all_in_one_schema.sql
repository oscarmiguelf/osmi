-- ---------------------------------------------------------------------
-- cash_audit (payment methods, movement types and registers)
--   Movements, balances, sessions and cuts are already their own history.
--   changed_by NULL = system / seed.
-- ---------------------------------------------------------------------
CREATE TABLE cash_audit (
    id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    entity_type    VARCHAR(20) NOT NULL,
    entity_id      UUID        NOT NULL,
    action         VARCHAR(10) NOT NULL,                 -- INSERT | UPDATE | DELETE | RESTORE
    changed_by     UUID        REFERENCES users (id) ON DELETE SET NULL,
    changed_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    changed_fields TEXT[],
    old_data       JSONB,
    new_data       JSONB,

    CONSTRAINT chk_cash_audit_entity CHECK (entity_type IN
        ('payment_method', 'cash_movement_type', 'cash_register')),
    CONSTRAINT chk_cash_audit_action CHECK (action IN ('INSERT', 'UPDATE', 'DELETE', 'RESTORE'))
);

CREATE INDEX idx_cash_audit_entity ON cash_audit (entity_type, entity_id, changed_at DESC);
CREATE INDEX idx_cash_audit_user   ON cash_audit (changed_by, changed_at DESC);

CREATE OR REPLACE FUNCTION fn_cash_audit()
RETURNS TRIGGER AS $$
DECLARE
    v_entity  TEXT  := TG_ARGV[0];
    v_new     JSONB := TO_JSONB(NEW);
    v_old     JSONB;
    v_action  TEXT;
    v_user_id UUID;
    v_changed TEXT[];
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO cash_audit (entity_type, entity_id, action, changed_by, new_data)
        VALUES (v_entity, NEW.id, 'INSERT', NEW.created_by, v_new);
        RETURN NEW;
    END IF;

    v_old := TO_JSONB(OLD);

    -- Skip no-op updates
    IF v_new - 'updated_at' - 'updated_by' = v_old - 'updated_at' - 'updated_by' THEN
        RETURN NEW;
    END IF;

    IF (v_old ->> 'deleted_at') IS NULL AND (v_new ->> 'deleted_at') IS NOT NULL THEN
        v_action  := 'DELETE';
        v_user_id := (v_new ->> 'deleted_by')::UUID;
    ELSIF (v_old ->> 'deleted_at') IS NOT NULL AND (v_new ->> 'deleted_at') IS NULL THEN
        v_action  := 'RESTORE';
        v_user_id := (v_new ->> 'updated_by')::UUID;
    ELSE
        v_action  := 'UPDATE';
        v_user_id := (v_new ->> 'updated_by')::UUID;
    END IF;

    SELECT ARRAY_AGG(n.key ORDER BY n.key)
      INTO v_changed
      FROM JSONB_EACH(v_new) n
      JOIN JSONB_EACH(v_old) o USING (key)
     WHERE n.value IS DISTINCT FROM o.value
       AND n.key <> 'updated_at';

    INSERT INTO cash_audit (entity_type, entity_id, action, changed_by, changed_fields, old_data, new_data)
    VALUES (v_entity, NEW.id, v_action, v_user_id, v_changed, v_old, v_new);

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

