-- ---------------------------------------------------------------------
-- Totals check, deferred to COMMIT:
--   * a quote must have at least one item
--   * quotes.subtotal must equal SUM(quote_items.line_total)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_quote_check_totals()
RETURNS TRIGGER AS $$
DECLARE
    v_quote_id UUID;
    v_count    INTEGER;
    v_sum      NUMERIC(12,2);
    v_subtotal NUMERIC(12,2);
BEGIN
    v_quote_id := CASE TG_TABLE_NAME WHEN 'quotes' THEN NEW.id ELSE (TO_JSONB(NEW) ->> 'quote_id')::UUID END;  -- NEW.quote_id would fail on the header table

    SELECT subtotal INTO v_subtotal FROM quotes WHERE id = v_quote_id;
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    SELECT COUNT(*), COALESCE(SUM(line_total), 0) INTO v_count, v_sum
      FROM quote_items WHERE quote_id = v_quote_id;

    IF v_count = 0 THEN
        RAISE EXCEPTION 'Quote % must have at least one item', v_quote_id;
    END IF;
    IF v_sum <> v_subtotal THEN
        RAISE EXCEPTION 'Quote %: subtotal % does not match the sum of its items %', v_quote_id, v_subtotal, v_sum;
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_quotes_check_totals
    AFTER INSERT ON quotes
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_quote_check_totals();
CREATE CONSTRAINT TRIGGER trg_quote_items_check_totals
    AFTER INSERT ON quote_items
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_quote_check_totals();

