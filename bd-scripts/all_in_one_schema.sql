-- ---------------------------------------------------------------------
-- Totals check, deferred to COMMIT:
--   * a purchase must have at least one item
--   * purchases.total must equal SUM(purchase_items.line_total)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_purchase_check_totals()
RETURNS TRIGGER AS $$
DECLARE
    v_purchase_id UUID;
    v_count       INTEGER;
    v_sum         NUMERIC(12,2);
    v_total       NUMERIC(12,2);
BEGIN
    v_purchase_id := CASE TG_TABLE_NAME WHEN 'purchases' THEN NEW.id ELSE (TO_JSONB(NEW) ->> 'purchase_id')::UUID END;  -- NEW.purchase_id would fail on the header table

    SELECT total INTO v_total FROM purchases WHERE id = v_purchase_id;
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    SELECT COUNT(*), COALESCE(SUM(line_total), 0)
      INTO v_count, v_sum
      FROM purchase_items WHERE purchase_id = v_purchase_id;

    IF v_count = 0 THEN
        RAISE EXCEPTION 'Purchase % must have at least one item', v_purchase_id;
    END IF;

    IF v_sum <> v_total THEN
        RAISE EXCEPTION 'Purchase %: total % does not match the sum of its items %', v_purchase_id, v_total, v_sum;
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

