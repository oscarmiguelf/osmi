    -- refunds move money in the register: the user must be occupying it
    PERFORM 1 FROM cash_register_sessions
     WHERE cash_register_id = NEW.cash_register_id AND user_id = NEW.created_by AND ended_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'User % is not occupying cash register %', NEW.created_by, NEW.cash_register_id;
    END IF;

    NEW.folio := fn_next_folio(v_branch, 'sale_return');
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

