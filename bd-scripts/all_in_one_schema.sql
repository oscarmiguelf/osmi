-- Generic audit trigger (same pattern as the other modules)
--   INSERT  -> user = created_by
--   UPDATE  -> user = updated_by   (the app MUST set it on every update)
--   DELETE  -> logical (void): deleted_at NULL -> value, user = deleted_by
--   RESTORE -> logical: deleted_at value -> NULL, user = updated_by
CREATE OR REPLACE FUNCTION fn_purchases_audit()
RETURNS TRIGGER AS $$
DECLARE
    v_entity      TEXT  := TG_ARGV[0];
    v_new         JSONB := TO_JSONB(NEW);
    v_old         JSONB;
    v_purchase_id UUID;
    v_action      TEXT;
    v_user_id     UUID;
    v_changed     TEXT[];
BEGIN
    IF v_entity = 'purchase' THEN
        v_purchase_id := NEW.id;
    ELSE
        v_purchase_id := (v_new ->> 'purchase_id')::UUID;
    END IF;

    IF TG_OP = 'INSERT' THEN
