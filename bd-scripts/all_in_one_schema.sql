-- ---------------------------------------------------------------------
-- SOFT DELETE ENFORCEMENT
--   Physical DELETE is blocked on business tables. To delete a row:
--     UPDATE <table> SET deleted_at = NOW(), deleted_by = :user_id WHERE id = ...;
--   To restore: SET deleted_at = NULL, deleted_by = NULL.
--   (Technical tables such as refresh_tokens and the grant tables
--    user_modules / user_module_permissions are still physically deleted.)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION prevent_hard_delete()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'Physical DELETE is not allowed on %. Set deleted_at / deleted_by instead.', TG_TABLE_NAME;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_users_no_hard_delete
    BEFORE DELETE ON users FOR EACH ROW EXECUTE FUNCTION prevent_hard_delete();
CREATE TRIGGER trg_modules_no_hard_delete
    BEFORE DELETE ON modules FOR EACH ROW EXECUTE FUNCTION prevent_hard_delete();
CREATE TRIGGER trg_permissions_no_hard_delete
    BEFORE DELETE ON permissions FOR EACH ROW EXECUTE FUNCTION prevent_hard_delete();

-- deleted_by can only be set when deleted_at is set
ALTER TABLE users       ADD CONSTRAINT chk_users_deleted       CHECK (deleted_at IS NOT NULL OR deleted_by IS NULL);
ALTER TABLE modules     ADD CONSTRAINT chk_modules_deleted     CHECK (deleted_at IS NOT NULL OR deleted_by IS NULL);
ALTER TABLE permissions ADD CONSTRAINT chk_permissions_deleted CHECK (deleted_at IS NOT NULL OR deleted_by IS NULL);

-- When a user is soft-deleted, kill all their sessions immediately
CREATE OR REPLACE FUNCTION fn_users_revoke_tokens_on_delete()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE refresh_tokens
       SET revoked_at = NOW(), revoked_reason = 'admin'
     WHERE user_id = NEW.id AND revoked_at IS NULL;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_users_revoke_tokens_on_delete
    AFTER UPDATE OF deleted_at ON users
    FOR EACH ROW
    WHEN (OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL)
    EXECUTE FUNCTION fn_users_revoke_tokens_on_delete();

