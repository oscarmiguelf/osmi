-- ---------------------------------------------------------------------
-- Validations shared by insert and update
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_appointments_check_people(p_row appointments)
RETURNS VOID AS $$
BEGIN
    IF p_row.assigned_to IS NOT NULL THEN
        IF NOT fn_user_in_branch(p_row.assigned_to, p_row.branch_id) THEN
            RAISE EXCEPTION 'User % (assigned) does not belong to the branch of the appointment', p_row.assigned_to;
        END IF;
        IF p_row.status NOT IN ('SCHEDULED', 'CONFIRMED') THEN
            RETURN;                                       -- closing an appointment never clashes
        END IF;
        -- The same person can't attend two open appointments at the same time
        PERFORM 1 FROM appointments a
         WHERE a.assigned_to = p_row.assigned_to AND a.id <> p_row.id
           AND a.status IN ('SCHEDULED', 'CONFIRMED')
           AND a.starts_at < p_row.ends_at AND a.ends_at > p_row.starts_at;
        IF FOUND THEN
            RAISE EXCEPTION 'The assigned person already has an appointment at that time';
        END IF;
    END IF;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION fn_appointments_before_insert()
RETURNS TRIGGER AS $$
BEGIN
    PERFORM 1 FROM branches WHERE id = NEW.branch_id AND deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Branch % does not exist or is deleted', NEW.branch_id;
    END IF;
    IF NOT fn_user_in_branch(NEW.created_by, NEW.branch_id) THEN
        RAISE EXCEPTION 'User % does not belong to branch %', NEW.created_by, NEW.branch_id;
    END IF;
    PERFORM 1 FROM customers WHERE id = NEW.customer_id AND deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Customer % does not exist or is deleted', NEW.customer_id;
    END IF;
    IF NEW.status NOT IN ('SCHEDULED', 'CONFIRMED') THEN
        RAISE EXCEPTION 'An appointment starts as SCHEDULED or CONFIRMED, not %', NEW.status;
    END IF;
    NEW.reschedule_count := 0;
    NEW.updated_by := COALESCE(NEW.updated_by, NEW.created_by);
    PERFORM fn_appointments_check_people(NEW);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_appointments_before_insert
    BEFORE INSERT ON appointments FOR EACH ROW EXECUTE FUNCTION fn_appointments_before_insert();

-- Status changes allowed:
--   SCHEDULED -> CONFIRMED | COMPLETED | CANCELLED | NO_SHOW
--   CONFIRMED -> SCHEDULED (only by rescheduling) | COMPLETED | CANCELLED | NO_SHOW
--   COMPLETED / CANCELLED / NO_SHOW -> (none: final)
CREATE OR REPLACE FUNCTION fn_appointments_before_update()
RETURNS TRIGGER AS $$
DECLARE
    v_moved BOOLEAN := NEW.starts_at IS DISTINCT FROM OLD.starts_at OR NEW.ends_at IS DISTINCT FROM OLD.ends_at;
BEGIN
    IF NEW.branch_id   IS DISTINCT FROM OLD.branch_id
    OR NEW.customer_id IS DISTINCT FROM OLD.customer_id
    OR NEW.created_by  IS DISTINCT FROM OLD.created_by
    OR NEW.reschedule_count IS DISTINCT FROM OLD.reschedule_count THEN
        RAISE EXCEPTION 'Branch, customer, creator and reschedule count of an appointment cannot be changed';
    END IF;

    IF OLD.status IN ('COMPLETED', 'CANCELLED', 'NO_SHOW') THEN
        RAISE EXCEPTION 'A % appointment cannot be modified', OLD.status;
    END IF;

    IF NOT fn_user_in_branch(NEW.updated_by, NEW.branch_id) THEN
        RAISE EXCEPTION 'User % does not belong to the branch of the appointment', NEW.updated_by;
    END IF;

    IF v_moved THEN
        IF NEW.status NOT IN ('SCHEDULED', 'CONFIRMED') THEN
            RAISE EXCEPTION 'Only an open appointment can be rescheduled';
        END IF;
        NEW.reschedule_count := OLD.reschedule_count + 1;
        NEW.status := 'SCHEDULED';                        -- a new time has to be confirmed again
    ELSIF NEW.status IS DISTINCT FROM OLD.status AND NEW.status NOT IN ('CONFIRMED', 'COMPLETED', 'CANCELLED', 'NO_SHOW') THEN
        RAISE EXCEPTION 'Invalid appointment status change: % -> %', OLD.status, NEW.status;  -- back to SCHEDULED only by rescheduling
    END IF;

    IF NEW.status = 'CANCELLED' AND BTRIM(COALESCE(NEW.cancel_reason, '')) = '' THEN
        RAISE EXCEPTION 'Say why the appointment is cancelled';
    END IF;

    PERFORM fn_appointments_check_people(NEW);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_appointments_before_update
    BEFORE UPDATE ON appointments FOR EACH ROW EXECUTE FUNCTION fn_appointments_before_update();

-- History: creation, reschedules (old -> new times + reason), status changes, other edits.
-- The reason of a reschedule travels in the transaction setting app.appointment_reason.
CREATE OR REPLACE FUNCTION fn_appointments_history()
RETURNS TRIGGER AS $$
DECLARE
    v_reason  TEXT := NULLIF(current_setting('app.appointment_reason', TRUE), '');
    v_changed TEXT[];
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO appointment_history (appointment_id, action, to_status, to_starts_at, to_ends_at, changed_by)
        VALUES (NEW.id, 'CREATED', NEW.status, NEW.starts_at, NEW.ends_at, NEW.created_by);
        RETURN NEW;
    END IF;

    IF NEW.starts_at IS DISTINCT FROM OLD.starts_at OR NEW.ends_at IS DISTINCT FROM OLD.ends_at THEN
        INSERT INTO appointment_history (appointment_id, action, from_status, to_status, from_starts_at, from_ends_at,
                                         to_starts_at, to_ends_at, reason, changed_by)
        VALUES (NEW.id, 'RESCHEDULED', OLD.status, NEW.status, OLD.starts_at, OLD.ends_at, NEW.starts_at, NEW.ends_at,
                v_reason, NEW.updated_by);
    ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
        INSERT INTO appointment_history (appointment_id, action, from_status, to_status, reason, changed_by)
        VALUES (NEW.id, 'STATUS', OLD.status, NEW.status, NEW.cancel_reason, NEW.updated_by);
    ELSE
        SELECT ARRAY_AGG(n.key ORDER BY n.key) INTO v_changed
          FROM JSONB_EACH(TO_JSONB(NEW)) n JOIN JSONB_EACH(TO_JSONB(OLD)) o USING (key)
         WHERE n.value IS DISTINCT FROM o.value AND n.key NOT IN ('updated_at', 'updated_by');
        IF v_changed IS NOT NULL THEN
            INSERT INTO appointment_history (appointment_id, action, changed_fields, changed_by)
            VALUES (NEW.id, 'UPDATED', v_changed, NEW.updated_by);
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_appointments_history
    AFTER INSERT OR UPDATE ON appointments FOR EACH ROW EXECUTE FUNCTION fn_appointments_history();

