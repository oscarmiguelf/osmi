-- ---------------------------------------------------------------------
-- Apply each movement to the balance (runs BEFORE the row is inserted)
--   1) register, payment method and movement type must exist and not be deleted
--   2) the user must belong to the register's branch
--   3) credit methods are rejected; a movement linked to a sale can only come from
--      sale payments / returns, and the sale must be from the same branch
--   4) locks the balance row (concurrent movements are serialized), updates or
--      creates it, and stores balance_before / balance_after in the movement
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_cash_movement_apply()
RETURNS TRIGGER AS $$
DECLARE
    v_branch UUID;
    v_before NUMERIC(12,2);
    v_after  NUMERIC(12,2);
BEGIN
    SELECT branch_id INTO v_branch
      FROM cash_registers
     WHERE id = NEW.cash_register_id AND deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Cash register % does not exist or is deleted', NEW.cash_register_id;
    END IF;

    IF NOT fn_user_in_branch(NEW.created_by, v_branch) THEN
        RAISE EXCEPTION 'User % does not belong to the branch of cash register %', NEW.created_by, NEW.cash_register_id;
    END IF;

    PERFORM 1 FROM payment_methods WHERE id = NEW.payment_method_id AND deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Payment method % does not exist or is deleted', NEW.payment_method_id;
    END IF;

    PERFORM 1 FROM cash_movement_types WHERE id = NEW.movement_type_id AND deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Cash movement type % does not exist or is deleted', NEW.movement_type_id;
    END IF;

    -- Credit ("on account") never moves money in a register
    PERFORM 1 FROM payment_methods WHERE id = NEW.payment_method_id AND is_credit;
    IF FOUND THEN
        RAISE EXCEPTION 'The credit payment method does not move money in a cash register';
    END IF;

    -- Movements tied to a sale come only from sale payments and returns
    IF NEW.sale_id IS NOT NULL THEN
        IF COALESCE(current_setting('app.sale_cash', TRUE), 'off') <> 'on' THEN
            RAISE EXCEPTION 'Cash movements linked to a sale are created automatically by sale payments and returns';
        END IF;

        PERFORM 1 FROM sales WHERE id = NEW.sale_id AND branch_id = v_branch;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Sale % does not belong to the branch of this cash register', NEW.sale_id;
        END IF;
    END IF;

    -- Allow the balance to change inside this step
    PERFORM set_config('app.cash_movement', 'on', TRUE);

    SELECT balance INTO v_before
      FROM cash_register_balances
     WHERE cash_register_id = NEW.cash_register_id
       AND payment_method_id = NEW.payment_method_id
       FOR UPDATE;

    IF NOT FOUND THEN
        v_before := 0;
        v_after  := NEW.amount;
        INSERT INTO cash_register_balances (cash_register_id, payment_method_id, balance)
        VALUES (NEW.cash_register_id, NEW.payment_method_id, v_after);
    ELSE
        v_after := v_before + NEW.amount;
        UPDATE cash_register_balances
           SET balance = v_after, updated_at = NOW()
         WHERE cash_register_id = NEW.cash_register_id
           AND payment_method_id = NEW.payment_method_id;
    END IF;

    PERFORM set_config('app.cash_movement', 'off', TRUE);

    NEW.balance_before := v_before;
    NEW.balance_after  := v_after;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

