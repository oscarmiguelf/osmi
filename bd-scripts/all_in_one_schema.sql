-- ---------------------------------------------------------------------
-- sales: validations on INSERT
--   branch, register and customer must be active; the seller must belong to the
--   branch and occupy the register; the folio is assigned here
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_sales_before_insert()
RETURNS TRIGGER AS $$
DECLARE
    v_status TEXT;
BEGIN
    PERFORM 1 FROM branches WHERE id = NEW.branch_id AND deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Branch % does not exist or is deleted', NEW.branch_id;
    END IF;

    IF NOT fn_user_in_branch(NEW.created_by, NEW.branch_id) THEN
        RAISE EXCEPTION 'User % does not belong to branch %', NEW.created_by, NEW.branch_id;
    END IF;

    PERFORM 1 FROM cash_registers WHERE id = NEW.cash_register_id AND deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Cash register % does not exist or is deleted', NEW.cash_register_id;
    END IF;

    -- The seller must be the user currently occupying that register
    PERFORM 1 FROM cash_register_sessions
     WHERE cash_register_id = NEW.cash_register_id
       AND user_id = NEW.created_by
       AND ended_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'User % is not occupying cash register %', NEW.created_by, NEW.cash_register_id;
    END IF;

    IF NEW.customer_id IS NOT NULL THEN
        PERFORM 1 FROM customers WHERE id = NEW.customer_id AND deleted_at IS NULL;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Customer % does not exist or is deleted', NEW.customer_id;
        END IF;
    END IF;

    SELECT name INTO v_status FROM sale_statuses WHERE id = NEW.status_id AND deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Sale status % does not exist or is deleted', NEW.status_id;
    END IF;
    IF v_status NOT IN ('PAID', 'PENDING') THEN
        RAISE EXCEPTION 'A sale starts as PAID (no credit portion) or PENDING (with a credit portion), not %', v_status;
    END IF;

    NEW.folio := fn_next_folio(NEW.branch_id, 'sale');

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

