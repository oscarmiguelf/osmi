-- ---------------------------------------------------------------------
-- AUTOMATIC STOCK (sale side)
--   Sale item inserted -> 'Sale' movement(s), NEGATIVE quantity, in the sale's branch:
--     * normal product (type tracks_stock)  -> one movement for the product
--     * kit (type is_kit)                   -> one movement per component:
--                                              item quantity x component quantity
--     * service / not tracked               -> nothing
--   Each movement keeps sale_item_id, so a return can give back exactly what was taken.
--   The inventory trigger rejects the movement if the branch lacks stock.
--   (Stock coming back is handled in returns_schema.sql.)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_sale_items_apply_stock()
RETURNS TRIGGER AS $$
DECLARE
    v_branch  UUID;
    v_type    UUID;
    v_is_kit  BOOLEAN;
    v_tracks  BOOLEAN;
    v_comp    RECORD;
BEGIN
    SELECT t.is_kit, t.tracks_stock
      INTO v_is_kit, v_tracks
      FROM products p
      JOIN product_types t ON t.id = p.product_type_id
     WHERE p.id = NEW.product_id;

    IF NOT v_is_kit AND NOT v_tracks THEN
        RETURN NEW;                                       -- e.g. a service: no stock
    END IF;

    SELECT branch_id INTO v_branch FROM sales WHERE id = NEW.sale_id;

    SELECT id INTO v_type FROM inventory_movement_types WHERE name = 'Sale' AND deleted_at IS NULL;
    IF v_type IS NULL THEN
        RAISE EXCEPTION 'Inventory movement type ''Sale'' does not exist';
    END IF;

    PERFORM set_config('app.sale_stock', 'on', TRUE);

    IF v_is_kit THEN
        FOR v_comp IN
            SELECT kc.component_product_id, kc.quantity
              FROM kit_components kc
              JOIN products cp      ON cp.id = kc.component_product_id AND cp.deleted_at IS NULL
              JOIN product_types ct ON ct.id = cp.product_type_id AND ct.tracks_stock
             WHERE kc.kit_product_id = NEW.product_id AND kc.deleted_at IS NULL
        LOOP
            INSERT INTO inventory_movements (branch_id, product_id, movement_type_id, quantity, sale_id, sale_item_id, created_by)
            VALUES (v_branch, v_comp.component_product_id, v_type,
                    -ROUND(NEW.quantity * v_comp.quantity, 3), NEW.sale_id, NEW.id, NEW.created_by);
        END LOOP;
    ELSE
        INSERT INTO inventory_movements (branch_id, product_id, movement_type_id, quantity, sale_id, sale_item_id, created_by)
        VALUES (v_branch, NEW.product_id, v_type, -NEW.quantity, NEW.sale_id, NEW.id, NEW.created_by);
    END IF;

    PERFORM set_config('app.sale_stock', 'off', TRUE);

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_sale_items_apply_stock
    AFTER INSERT ON sale_items
    FOR EACH ROW EXECUTE FUNCTION fn_sale_items_apply_stock();

