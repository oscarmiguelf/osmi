CREATE OR REPLACE FUNCTION fn_quotes_audit()
RETURNS TRIGGER AS $$
DECLARE
    v_entity   TEXT  := TG_ARGV[0];
    v_new      JSONB := TO_JSONB(NEW);
    v_old      JSONB;
    v_quote_id UUID;
    v_action   TEXT;
    v_user_id  UUID;
    v_changed  TEXT[];
BEGIN
    IF v_entity = 'quote' THEN
        v_quote_id := NEW.id;
    ELSIF v_entity = 'quote_item' THEN
        v_quote_id := (v_new ->> 'quote_id')::UUID;
    END IF;

    IF TG_OP = 'INSERT' THEN
        INSERT INTO quotes_audit (entity_type, entity_id, quote_id, action, changed_by, new_data)
        VALUES (v_entity, NEW.id, v_quote_id, 'INSERT', NEW.created_by, v_new);
        RETURN NEW;
    END IF;

    v_old := TO_JSONB(OLD);

    IF v_new - 'updated_at' - 'updated_by' = v_old - 'updated_at' - 'updated_by' THEN
        RETURN NEW;
    END IF;

    IF (v_old ->> 'deleted_at') IS NULL AND (v_new ->> 'deleted_at') IS NOT NULL THEN
        v_action  := 'DELETE';
        v_user_id := (v_new ->> 'deleted_by')::UUID;
    ELSIF (v_old ->> 'deleted_at') IS NOT NULL AND (v_new ->> 'deleted_at') IS NULL THEN
        v_action  := 'RESTORE';
        v_user_id := (v_new ->> 'updated_by')::UUID;
    ELSE
        v_action  := 'UPDATE';
        v_user_id := (v_new ->> 'updated_by')::UUID;
    END IF;

    SELECT ARRAY_AGG(n.key ORDER BY n.key) INTO v_changed
      FROM JSONB_EACH(v_new) n JOIN JSONB_EACH(v_old) o USING (key)
     WHERE n.value IS DISTINCT FROM o.value AND n.key <> 'updated_at';

    INSERT INTO quotes_audit (entity_type, entity_id, quote_id, action, changed_by, changed_fields, old_data, new_data)
    VALUES (v_entity, NEW.id, v_quote_id, v_action, v_user_id, v_changed, v_old, v_new);

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

