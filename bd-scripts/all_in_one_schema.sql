-- Stock back in + sale becomes RETURNED when everything has been returned
CREATE OR REPLACE FUNCTION fn_sale_return_items_after_insert()
RETURNS TRIGGER AS $$
DECLARE
    v_branch     UUID;
    v_type       UUID;
    v_item_qty   NUMERIC(14,3);
    v_cum_after  NUMERIC(14,3);
    v_cum_before NUMERIC(14,3);
    v_back       NUMERIC(14,3);
    v_mov        RECORD;
    v_folio      TEXT;
BEGIN
    SELECT branch_id, folio INTO v_branch, v_folio FROM sale_returns WHERE id = NEW.sale_return_id;
    SELECT quantity INTO v_item_qty FROM sale_items WHERE id = NEW.sale_item_id;

    SELECT SUM(quantity) INTO v_cum_after FROM sale_return_items WHERE sale_item_id = NEW.sale_item_id;
    v_cum_before := v_cum_after - NEW.quantity;

    SELECT id INTO v_type FROM inventory_movement_types WHERE name = 'Return' AND deleted_at IS NULL;
    IF v_type IS NULL THEN
        RAISE EXCEPTION 'Inventory movement type ''Return'' does not exist';
    END IF;

    -- Give back exactly what the sale took out of this item (product, or kit components)
    PERFORM set_config('app.sale_stock', 'on', TRUE);
    FOR v_mov IN
        SELECT m.product_id, -m.quantity AS taken
          FROM inventory_movements m
          JOIN inventory_movement_types t ON t.id = m.movement_type_id AND t.name = 'Sale'
         WHERE m.sale_item_id = NEW.sale_item_id
    LOOP
        v_back := ROUND(v_mov.taken * v_cum_after  / v_item_qty, 3)
                - ROUND(v_mov.taken * v_cum_before / v_item_qty, 3);
        IF v_back > 0 THEN
            INSERT INTO inventory_movements
                (branch_id, product_id, movement_type_id, quantity, sale_id, sale_item_id, notes, created_by)
            VALUES (v_branch, v_mov.product_id, v_type, v_back, NEW.sale_id, NEW.sale_item_id,
                    'Return ' || v_folio, NEW.created_by);
        END IF;
    END LOOP;
    PERFORM set_config('app.sale_stock', 'off', TRUE);

    -- Everything returned? -> the sale is RETURNED
    PERFORM 1
      FROM sale_items i
     WHERE i.sale_id = NEW.sale_id
       AND i.quantity > COALESCE((SELECT SUM(r.quantity) FROM sale_return_items r WHERE r.sale_item_id = i.id), 0);
    IF NOT FOUND THEN
        PERFORM fn_set_sale_status(NEW.sale_id, 'RETURNED', NEW.created_by);
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_sale_return_items_after_insert
    AFTER INSERT ON sale_return_items
    FOR EACH ROW EXECUTE FUNCTION fn_sale_return_items_after_insert();

-- ---------------------------------------------------------------------
-- sale_return_refunds: validate and apply (cash out / cancel customer debt)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_sale_return_refunds_before_insert()
RETURNS TRIGGER AS $$
DECLARE
    v_ret         RECORD;
    v_is_credit   BOOLEAN;
    v_customer    UUID;
    v_outstanding NUMERIC(12,2);
BEGIN
    SELECT sale_id, created_at INTO v_ret FROM sale_returns WHERE id = NEW.sale_return_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Return % does not exist', NEW.sale_return_id;
    END IF;
    IF v_ret.created_at <> NOW() THEN
        RAISE EXCEPTION 'Refunds must be registered in the same transaction as the return';
    END IF;

    SELECT is_credit INTO v_is_credit FROM payment_methods
     WHERE id = NEW.payment_method_id AND deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Payment method % does not exist or is deleted', NEW.payment_method_id;
    END IF;

    IF v_is_credit THEN
        SELECT customer_id INTO v_customer FROM sales WHERE id = v_ret.sale_id;
        IF v_customer IS NULL THEN
            RAISE EXCEPTION 'The sale has no customer, so there is no credit to cancel';
        END IF;

        v_outstanding := fn_sale_credit_outstanding(v_ret.sale_id);
        IF NEW.amount > v_outstanding THEN
            RAISE EXCEPTION 'Credit refund (%) is greater than the credit still owed on the sale (%)', NEW.amount, v_outstanding;
        END IF;
    END IF;

    NEW.sale_id := v_ret.sale_id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_sale_return_refunds_before_insert
    BEFORE INSERT ON sale_return_refunds
    FOR EACH ROW EXECUTE FUNCTION fn_sale_return_refunds_before_insert();

CREATE OR REPLACE FUNCTION fn_sale_return_refunds_after_insert()
RETURNS TRIGGER AS $$
DECLARE
    v_is_credit BOOLEAN;
    v_register  UUID;
    v_type      UUID;
    v_customer  UUID;
    v_folio     TEXT;
BEGIN
    SELECT is_credit INTO v_is_credit FROM payment_methods WHERE id = NEW.payment_method_id;
    SELECT cash_register_id, folio INTO v_register, v_folio FROM sale_returns WHERE id = NEW.sale_return_id;

    IF v_is_credit THEN
        SELECT customer_id INTO v_customer FROM sales WHERE id = NEW.sale_id;
        PERFORM fn_customer_credit_move(v_customer, NEW.sale_id, 'return', -NEW.amount, NEW.created_by);
    ELSE
        SELECT id INTO v_type FROM cash_movement_types WHERE name = 'Return' AND deleted_at IS NULL;
        IF v_type IS NULL THEN
            RAISE EXCEPTION 'Cash movement type ''Return'' does not exist';
        END IF;

        PERFORM set_config('app.sale_cash', 'on', TRUE);
        INSERT INTO cash_register_movements
            (cash_register_id, payment_method_id, movement_type_id, amount, sale_id, notes, created_by)
        VALUES (v_register, NEW.payment_method_id, v_type, -NEW.amount, NEW.sale_id,
                'Refund ' || v_folio, NEW.created_by);
        PERFORM set_config('app.sale_cash', 'off', TRUE);
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_sale_return_refunds_after_insert
    AFTER INSERT ON sale_return_refunds
    FOR EACH ROW EXECUTE FUNCTION fn_sale_return_refunds_after_insert();

-- ---------------------------------------------------------------------
-- Check deferred to COMMIT:
--   * the return has at least one item
--   * refund_total = sum of the items = sum of the refunds
--   * a RETURNED sale can't keep credit owed
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_sale_return_check()
RETURNS TRIGGER AS $$
DECLARE
    v_return_id  UUID;
    v_sale_id    UUID;
    v_total      NUMERIC(12,2);
    v_items      NUMERIC(12,2);
    v_item_count INTEGER;
    v_refunds    NUMERIC(12,2);
    v_status     TEXT;
BEGIN
    v_return_id := CASE TG_TABLE_NAME WHEN 'sale_returns' THEN NEW.id ELSE (TO_JSONB(NEW) ->> 'sale_return_id')::UUID END;  -- NEW.sale_return_id would fail on the header table

    SELECT refund_total, sale_id INTO v_total, v_sale_id FROM sale_returns WHERE id = v_return_id;
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    SELECT COUNT(*), COALESCE(SUM(refund_amount), 0) INTO v_item_count, v_items
      FROM sale_return_items WHERE sale_return_id = v_return_id;
    SELECT COALESCE(SUM(amount), 0) INTO v_refunds
      FROM sale_return_refunds WHERE sale_return_id = v_return_id;

    IF v_item_count = 0 THEN
        RAISE EXCEPTION 'Return % must have at least one item', v_return_id;
    END IF;
    IF v_items <> v_total THEN
        RAISE EXCEPTION 'Return %: refund_total (%) does not match the sum of its items (%)', v_return_id, v_total, v_items;
    END IF;
    IF v_refunds <> v_total THEN
        RAISE EXCEPTION 'Return %: refunds (%) do not add up to refund_total (%)', v_return_id, v_refunds, v_total;
    END IF;

    SELECT st.name INTO v_status FROM sales s JOIN sale_statuses st ON st.id = s.status_id WHERE s.id = v_sale_id;
    IF v_status = 'RETURNED' AND fn_sale_credit_outstanding(v_sale_id) <> 0 THEN
        RAISE EXCEPTION 'Sale % is fully returned but still has credit owed: refund the credit portion with the Credit method', v_sale_id;
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_sale_returns_check
    AFTER INSERT ON sale_returns
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_sale_return_check();
CREATE CONSTRAINT TRIGGER trg_sale_return_items_check
    AFTER INSERT ON sale_return_items
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_sale_return_check();
CREATE CONSTRAINT TRIGGER trg_sale_return_refunds_check
    AFTER INSERT ON sale_return_refunds
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_sale_return_check();

