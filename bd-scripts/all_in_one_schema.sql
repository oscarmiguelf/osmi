CREATE TABLE quotes_audit (
    id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    entity_type    VARCHAR(20) NOT NULL,                 -- quote | quote_item | quote_status
    entity_id      UUID        NOT NULL,
    quote_id       UUID,
    action         VARCHAR(10) NOT NULL,
    changed_by     UUID        REFERENCES users (id) ON DELETE SET NULL,
    changed_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    changed_fields TEXT[],
    old_data       JSONB,
    new_data       JSONB,

    CONSTRAINT chk_quotes_audit_entity CHECK (entity_type IN ('quote', 'quote_item', 'quote_status')),
    CONSTRAINT chk_quotes_audit_action CHECK (action IN ('INSERT', 'UPDATE', 'DELETE', 'RESTORE'))
