-- The login flow (failed attempts, lockout, last login) runs with SET LOCAL app.auth_event = 'on':
-- those are security events already in login_audit, not admin changes, so they are not audited here.
CREATE OR REPLACE FUNCTION fn_users_audit()
RETURNS TRIGGER AS $$
DECLARE
    v_new     JSONB := TO_JSONB(NEW) - 'password_hash';
    v_old     JSONB;
    v_action  TEXT;
    v_user_id UUID;
    v_changed TEXT[];
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO users_audit (user_id, action, changed_by, new_data)
        VALUES (NEW.id, 'INSERT', NEW.created_by, v_new);
        RETURN NEW;
    END IF;

    IF COALESCE(current_setting('app.auth_event', TRUE), 'off') = 'on' THEN
        RETURN NEW;
    END IF;

    v_old := TO_JSONB(OLD) - 'password_hash';

    SELECT ARRAY_AGG(n.key ORDER BY n.key)
      INTO v_changed
      FROM JSONB_EACH(TO_JSONB(NEW)) n
      JOIN JSONB_EACH(TO_JSONB(OLD)) o USING (key)
     WHERE n.value IS DISTINCT FROM o.value
       AND n.key NOT IN ('updated_at', 'updated_by');

    IF v_changed IS NULL THEN  -- no-op update
        RETURN NEW;
    END IF;

    IF OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL THEN
        v_action  := 'DELETE';
        v_user_id := NEW.deleted_by;
    ELSIF OLD.deleted_at IS NOT NULL AND NEW.deleted_at IS NULL THEN
        v_action  := 'RESTORE';
        v_user_id := NEW.updated_by;
    ELSE
        v_action  := 'UPDATE';
        v_user_id := NEW.updated_by;
    END IF;

    INSERT INTO users_audit (user_id, action, changed_by, changed_fields, old_data, new_data)
    VALUES (NEW.id, v_action, v_user_id, v_changed, v_old, v_new);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

