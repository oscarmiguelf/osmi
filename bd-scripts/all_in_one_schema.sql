CREATE OR REPLACE FUNCTION fn_kit_components_validate()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.deleted_at IS NOT NULL THEN
        RETURN NEW;                                       -- removing a component is always allowed
    END IF;

    PERFORM 1 FROM products p JOIN product_types t ON t.id = p.product_type_id
     WHERE p.id = NEW.kit_product_id AND p.deleted_at IS NULL AND t.is_kit;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Product % is not an active kit (its type must have is_kit = TRUE)', NEW.kit_product_id;
    END IF;

    PERFORM 1 FROM products p JOIN product_types t ON t.id = p.product_type_id
     WHERE p.id = NEW.component_product_id AND p.deleted_at IS NULL AND NOT t.is_kit;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Component % must be an active product that is not a kit', NEW.component_product_id;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

