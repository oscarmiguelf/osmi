-- ---------------------------------------------------------------------
-- fn_calc_return_refund(sale_item_id, quantity): the refund the database will
-- calculate for returning `quantity` units of a sale item NOW. Use it to build
-- refund_total and the refund rows before inserting.
--   = net value of the line (after the sale-level discount) pro-rated by units;
--     the last units take whatever is left, so cents never get lost.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_calc_return_refund(p_sale_item_id UUID, p_quantity NUMERIC)
RETURNS NUMERIC AS $$
DECLARE
    v_item         RECORD;
    v_sale         RECORD;
    v_returned_qty NUMERIC(14,3);
    v_refunded     NUMERIC(12,2);
    v_line_net     NUMERIC(12,2);
BEGIN
    SELECT id, sale_id, quantity, line_total INTO v_item FROM sale_items WHERE id = p_sale_item_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Sale item % does not exist', p_sale_item_id;
    END IF;

    SELECT subtotal, total INTO v_sale FROM sales WHERE id = v_item.sale_id;

    SELECT COALESCE(SUM(quantity), 0), COALESCE(SUM(refund_amount), 0)
      INTO v_returned_qty, v_refunded
      FROM sale_return_items WHERE sale_item_id = p_sale_item_id;

    IF p_quantity <= 0 OR p_quantity > v_item.quantity - v_returned_qty THEN
        RAISE EXCEPTION 'Cannot return % units: only % of % are left to return for this item',
            p_quantity, v_item.quantity - v_returned_qty, v_item.quantity;
    END IF;

    v_line_net := CASE WHEN v_sale.subtotal = 0 THEN 0
                       ELSE ROUND(v_item.line_total * v_sale.total / v_sale.subtotal, 2) END;

    IF v_returned_qty + p_quantity = v_item.quantity THEN
        RETURN v_line_net - v_refunded;
    END IF;
    RETURN ROUND(v_line_net * p_quantity / v_item.quantity, 2);
END;
$$ LANGUAGE plpgsql STABLE;

