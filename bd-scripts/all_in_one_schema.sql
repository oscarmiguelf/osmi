-- ---------------------------------------------------------------------
-- transfers_audit
-- ---------------------------------------------------------------------
CREATE TABLE transfers_audit (
    id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    entity_type    VARCHAR(20) NOT NULL,                 -- transfer | transfer_item | transfer_status
    entity_id      UUID        NOT NULL,
    transfer_id    UUID,
    action         VARCHAR(10) NOT NULL,
    changed_by     UUID        REFERENCES users (id) ON DELETE SET NULL,
    changed_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    changed_fields TEXT[],
    old_data       JSONB,
    new_data       JSONB,

    CONSTRAINT chk_transfers_audit_entity CHECK (entity_type IN ('transfer', 'transfer_item', 'transfer_status')),
    CONSTRAINT chk_transfers_audit_action CHECK (action IN ('INSERT', 'UPDATE', 'DELETE', 'RESTORE'))
);

CREATE INDEX idx_transfers_audit_entity   ON transfers_audit (entity_type, entity_id, changed_at DESC);
CREATE INDEX idx_transfers_audit_transfer ON transfers_audit (transfer_id, changed_at DESC) WHERE transfer_id IS NOT NULL;
CREATE INDEX idx_transfers_audit_user     ON transfers_audit (changed_by, changed_at DESC);

CREATE OR REPLACE FUNCTION fn_transfers_audit()
RETURNS TRIGGER AS $$
DECLARE
    v_entity      TEXT  := TG_ARGV[0];
    v_new         JSONB := TO_JSONB(NEW);
    v_old         JSONB;
    v_transfer_id UUID;
    v_action      TEXT;
    v_user_id     UUID;
    v_changed     TEXT[];
BEGIN
    IF v_entity = 'transfer' THEN
        v_transfer_id := NEW.id;
    ELSIF v_entity = 'transfer_item' THEN
        v_transfer_id := (v_new ->> 'transfer_id')::UUID;
    END IF;

    IF TG_OP = 'INSERT' THEN
        INSERT INTO transfers_audit (entity_type, entity_id, transfer_id, action, changed_by, new_data)
        VALUES (v_entity, NEW.id, v_transfer_id, 'INSERT', NEW.created_by, v_new);
        RETURN NEW;
    END IF;

    v_old := TO_JSONB(OLD);

    IF v_new - 'updated_at' - 'updated_by' = v_old - 'updated_at' - 'updated_by' THEN
        RETURN NEW;
    END IF;

    IF (v_old ->> 'deleted_at') IS NULL AND (v_new ->> 'deleted_at') IS NOT NULL THEN
        v_action  := 'DELETE';
        v_user_id := (v_new ->> 'deleted_by')::UUID;
    ELSIF (v_old ->> 'deleted_at') IS NOT NULL AND (v_new ->> 'deleted_at') IS NULL THEN
        v_action  := 'RESTORE';
        v_user_id := (v_new ->> 'updated_by')::UUID;
    ELSE
        v_action  := 'UPDATE';
        v_user_id := (v_new ->> 'updated_by')::UUID;
    END IF;

    SELECT ARRAY_AGG(n.key ORDER BY n.key) INTO v_changed
      FROM JSONB_EACH(v_new) n JOIN JSONB_EACH(v_old) o USING (key)
     WHERE n.value IS DISTINCT FROM o.value AND n.key <> 'updated_at';

    INSERT INTO transfers_audit (entity_type, entity_id, transfer_id, action, changed_by, changed_fields, old_data, new_data)
    VALUES (v_entity, NEW.id, v_transfer_id, v_action, v_user_id, v_changed, v_old, v_new);

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_transfers_audit
    AFTER INSERT OR UPDATE ON transfers FOR EACH ROW EXECUTE FUNCTION fn_transfers_audit('transfer');
