-- ---------------------------------------------------------------------
-- transfers: validations on INSERT (always starts IN_TRANSIT)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_transfers_before_insert()
RETURNS TRIGGER AS $$
DECLARE
    v_status TEXT;
BEGIN
    PERFORM 1 FROM branches WHERE id = NEW.from_branch_id AND deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Origin branch % does not exist or is deleted', NEW.from_branch_id;
    END IF;
    PERFORM 1 FROM branches WHERE id = NEW.to_branch_id AND deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Destination branch % does not exist or is deleted', NEW.to_branch_id;
    END IF;

    IF NOT fn_user_in_branch(NEW.created_by, NEW.from_branch_id) THEN
        RAISE EXCEPTION 'User % does not belong to the origin branch', NEW.created_by;
    END IF;

    SELECT name INTO v_status FROM transfer_statuses WHERE id = NEW.status_id AND deleted_at IS NULL;
    IF v_status IS DISTINCT FROM 'IN_TRANSIT' THEN
        RAISE EXCEPTION 'A transfer starts as IN_TRANSIT';
    END IF;

    NEW.folio := fn_next_folio(NEW.from_branch_id, 'transfer');
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_transfers_before_insert
    BEFORE INSERT ON transfers FOR EACH ROW EXECUTE FUNCTION fn_transfers_before_insert();

-- ---------------------------------------------------------------------
-- transfers: validations on UPDATE
--   * only status_id, notes and updated_by can change
--   * IN_TRANSIT -> RECEIVED   by a user of the DESTINATION branch
--   * IN_TRANSIT -> CANCELLED  by a user of the ORIGIN branch
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_transfers_before_update()
RETURNS TRIGGER AS $$
DECLARE
    v_old TEXT;
    v_new TEXT;
BEGIN
    IF NEW.folio          IS DISTINCT FROM OLD.folio
    OR NEW.from_branch_id IS DISTINCT FROM OLD.from_branch_id
    OR NEW.to_branch_id   IS DISTINCT FROM OLD.to_branch_id
    OR NEW.created_by     IS DISTINCT FROM OLD.created_by THEN
        RAISE EXCEPTION 'Folio, branches and creator of a transfer cannot be changed';
    END IF;

    IF NEW.status_id IS DISTINCT FROM OLD.status_id THEN
        SELECT name INTO v_old FROM transfer_statuses WHERE id = OLD.status_id;
        SELECT name INTO v_new FROM transfer_statuses WHERE id = NEW.status_id AND deleted_at IS NULL;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Transfer status % does not exist or is deleted', NEW.status_id;
        END IF;

        IF v_old <> 'IN_TRANSIT' OR v_new NOT IN ('RECEIVED', 'CANCELLED') THEN
            RAISE EXCEPTION 'Invalid transfer status change: % -> %', v_old, v_new;
        END IF;

        IF v_new = 'RECEIVED' AND NOT fn_user_in_branch(NEW.updated_by, NEW.to_branch_id) THEN
            RAISE EXCEPTION 'Only a user of the destination branch can receive the transfer';
        END IF;
        IF v_new = 'CANCELLED' AND NOT fn_user_in_branch(NEW.updated_by, NEW.from_branch_id) THEN
            RAISE EXCEPTION 'Only a user of the origin branch can cancel the transfer';
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_transfers_before_update
    BEFORE UPDATE ON transfers FOR EACH ROW EXECUTE FUNCTION fn_transfers_before_update();

-- ---------------------------------------------------------------------
-- transfer_items: validations + stock OUT of the origin
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_transfer_items_before_insert()
RETURNS TRIGGER AS $$
DECLARE
    v_tr RECORD;
BEGIN
    SELECT t.created_at, st.name AS status INTO v_tr
      FROM transfers t JOIN transfer_statuses st ON st.id = t.status_id
     WHERE t.id = NEW.transfer_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Transfer % does not exist', NEW.transfer_id;
    END IF;
    IF v_tr.created_at <> NOW() THEN
        RAISE EXCEPTION 'Transfer items must be registered in the same transaction as the transfer';
    END IF;

    PERFORM 1
      FROM products p JOIN product_types t ON t.id = p.product_type_id
     WHERE p.id = NEW.product_id AND p.deleted_at IS NULL AND t.tracks_stock AND NOT t.is_kit;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Product % cannot be transferred: it must be an active product that tracks stock (not a service or a kit)', NEW.product_id;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_transfer_items_before_insert
    BEFORE INSERT ON transfer_items FOR EACH ROW EXECUTE FUNCTION fn_transfer_items_before_insert();

CREATE OR REPLACE FUNCTION fn_transfer_items_after_insert()
RETURNS TRIGGER AS $$
DECLARE
    v_from  UUID;
    v_folio TEXT;
    v_type  UUID;
BEGIN
    SELECT from_branch_id, folio INTO v_from, v_folio FROM transfers WHERE id = NEW.transfer_id;

    SELECT id INTO v_type FROM inventory_movement_types WHERE name = 'Transfer Out' AND deleted_at IS NULL;
    IF v_type IS NULL THEN
        RAISE EXCEPTION 'Inventory movement type ''Transfer Out'' does not exist';
    END IF;

    PERFORM set_config('app.transfer_stock', 'on', TRUE);
    INSERT INTO inventory_movements (branch_id, product_id, movement_type_id, quantity, transfer_id, reference, created_by)
    VALUES (v_from, NEW.product_id, v_type, -NEW.quantity, NEW.transfer_id, v_folio, NEW.created_by);
    PERFORM set_config('app.transfer_stock', 'off', TRUE);

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_transfer_items_after_insert
    AFTER INSERT ON transfer_items FOR EACH ROW EXECUTE FUNCTION fn_transfer_items_after_insert();

-- ---------------------------------------------------------------------
-- Status change: stock IN to the destination (RECEIVED) or back to the origin (CANCELLED)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_transfers_status_effects()
RETURNS TRIGGER AS $$
DECLARE
    v_status TEXT;
    v_branch UUID;
    v_type   UUID;
    v_item   RECORD;
BEGIN
    SELECT name INTO v_status FROM transfer_statuses WHERE id = NEW.status_id;

    SELECT id INTO v_type FROM inventory_movement_types WHERE name = 'Transfer In' AND deleted_at IS NULL;
    IF v_type IS NULL THEN
        RAISE EXCEPTION 'Inventory movement type ''Transfer In'' does not exist';
    END IF;

    v_branch := CASE v_status WHEN 'RECEIVED' THEN NEW.to_branch_id ELSE NEW.from_branch_id END;

    PERFORM set_config('app.transfer_stock', 'on', TRUE);
    FOR v_item IN SELECT product_id, quantity FROM transfer_items WHERE transfer_id = NEW.id
    LOOP
        INSERT INTO inventory_movements (branch_id, product_id, movement_type_id, quantity, transfer_id, reference, notes, created_by)
        VALUES (v_branch, v_item.product_id, v_type, v_item.quantity, NEW.id, NEW.folio,
                CASE v_status WHEN 'RECEIVED' THEN 'Transfer received' ELSE 'Transfer cancelled' END,
                NEW.updated_by);
    END LOOP;
    PERFORM set_config('app.transfer_stock', 'off', TRUE);

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

