-- #####################################################################
-- FILE: sales_schema.sql
-- #####################################################################
-- =====================================================================
-- Sales module: statuses, sales, sale items, automatic stock, audit
-- Target: PostgreSQL 13+
-- Depends on:
--   auth_schema.sql      -> users, set_updated_at(), prevent_hard_delete()
--   branches_schema.sql  -> branches, fn_user_in_branch()
--   customers_schema.sql -> customers
--   products_schema.sql  -> products, product_types, kit_components
--   inventory_schema.sql -> inventory_movements, prevent_modification()
--   cash_schema.sql      -> payment_methods, cash_registers, cash_register_sessions,
--                           cash_register_movements
--
-- Branches: every sale belongs to ONE branch and is made at ONE cash register of
-- that branch, by a user who belongs to the branch and currently occupies the register.
--
-- Stock moves AUTOMATICALLY (per branch, the product catalog is shared):
--   * inserting a sale item creates a 'Sale' inventory movement (stock OUT) in the
--     sale's branch, for products whose type has tracks_stock = TRUE
--   * KITS: selling a kit moves the stock of its COMPONENTS (kit_components), not the kit
--   * returns are registered in returns_schema.sql and put the stock back in
--   * if there is not enough stock in that branch, the whole sale is rejected
--   * movements linked to a sale can ONLY be created by these triggers (no duplicates)
--   * a sale must be RETURNED before it can be soft-deleted, so stock is never left out
--
-- Folio: every sale gets a readable number per branch, e.g. SUC1-000123.
--
-- Status is managed by the system, never by hand:
--   PAID    = fully paid at the sale (no credit portion)
--   PENDING = part of the sale is on the customer's credit (see payments_schema.sql)
--   PENDING -> PAID when the credit is paid off (abonos); -> RETURNED when everything
--   is returned (returns_schema.sql).
--
-- Payments (mixed methods, cash received/change, credit) -> payments_schema.sql
--
-- Fulfillment: every sale item is RESERVED or DELIVERED (fulfillment_statuses).
--   RESERVED -> DELIVERED is the only allowed change, and it is the ONLY edit
--   allowed on a sale item. It is recorded in sale_item_fulfillment_history.
--
-- Money rules:
--   line_total (sale_items) = ROUND(quantity * unit_price, 2) - discount
--   subtotal   (sales)      = SUM(line_total of its items)
--   total      (sales)      = subtotal - discount   (discount = extra discount on the whole sale)
-- =====================================================================


