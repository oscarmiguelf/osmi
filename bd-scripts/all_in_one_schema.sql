CREATE OR REPLACE FUNCTION fn_expenses_before_write()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        PERFORM 1 FROM branches WHERE id = NEW.branch_id AND deleted_at IS NULL;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Branch % does not exist or is deleted', NEW.branch_id;
        END IF;
        IF NOT fn_user_in_branch(NEW.created_by, NEW.branch_id) THEN
            RAISE EXCEPTION 'User % does not belong to branch %', NEW.created_by, NEW.branch_id;
        END IF;
    ELSE
        IF OLD.deleted_at IS NOT NULL THEN
            RAISE EXCEPTION 'This expense was voided and can no longer change';
        END IF;
        -- The amount is what the payments are measured against: void and record it again instead
        IF NEW.branch_id IS DISTINCT FROM OLD.branch_id OR NEW.amount IS DISTINCT FROM OLD.amount THEN
            RAISE EXCEPTION 'The branch and the amount of an expense can''t change';
        END IF;
    END IF;
    IF NEW.supplier_id IS NOT NULL AND NEW.supplier_id IS DISTINCT FROM (CASE WHEN TG_OP = 'UPDATE' THEN OLD.supplier_id END) THEN
        PERFORM 1 FROM suppliers WHERE id = NEW.supplier_id AND deleted_at IS NULL;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Supplier % does not exist or is deleted', NEW.supplier_id;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_expenses_before_write
    BEFORE INSERT OR UPDATE ON expenses FOR EACH ROW EXECUTE FUNCTION fn_expenses_before_write();

