-- ---------------------------------------------------------------------
-- refresh_tokens
--   * Only the SHA-256 hash of the token is stored, never the token itself
--   * family_id groups all tokens from the same login (rotation chain)
--   * session_started_at is copied on every rotation (absolute lifetime cap)
-- ---------------------------------------------------------------------
CREATE TABLE refresh_tokens (
    id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id            UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    family_id          UUID        NOT NULL,
    token_hash         CHAR(64)    NOT NULL UNIQUE,          -- hex SHA-256
    session_started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at         TIMESTAMPTZ NOT NULL,
    revoked_at         TIMESTAMPTZ,
    revoked_reason     VARCHAR(30),                          -- 'rotated', 'logout', 'reuse_detected', 'admin'
    replaced_by_id     UUID        REFERENCES refresh_tokens (id) ON DELETE SET NULL,
    user_agent         VARCHAR(500),
    ip_address         INET,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_refresh_tokens_revoked_reason
        CHECK (revoked_reason IS NULL OR revoked_reason IN ('rotated', 'logout', 'reuse_detected', 'admin'))
);

CREATE INDEX idx_refresh_tokens_user_id    ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_family_id  ON refresh_tokens (family_id);
CREATE INDEX idx_refresh_tokens_expires_at ON refresh_tokens (expires_at);

