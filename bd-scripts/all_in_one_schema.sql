-- ---------------------------------------------------------------------
-- Discount of a LINE for a promotion (money, rounded to 2 decimals)
--   PERCENT      qty * price * percent / 100
--   AMOUNT       qty * amount, never more than the line itself
--   BUY_X_GET_Y  FLOOR(qty / (buy + get)) * get * price   (the free units)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_promotion_discount(p_promotion_id UUID, p_quantity NUMERIC, p_unit_price NUMERIC)
RETURNS NUMERIC AS $$
DECLARE
    v_p     promotions%ROWTYPE;
    v_gross NUMERIC(12,2) := ROUND(p_quantity * p_unit_price, 2);
BEGIN
    SELECT * INTO v_p FROM promotions WHERE id = p_promotion_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Promotion % does not exist', p_promotion_id;
    END IF;

    RETURN CASE v_p.kind
        WHEN 'PERCENT'     THEN ROUND(v_gross * v_p.percent / 100, 2)
        WHEN 'AMOUNT'      THEN LEAST(ROUND(p_quantity * v_p.amount, 2), v_gross)
        WHEN 'BUY_X_GET_Y' THEN ROUND(FLOOR(p_quantity / (v_p.buy_quantity + v_p.get_quantity))
                                      * v_p.get_quantity * p_unit_price, 2)
    END;
END;
$$ LANGUAGE plpgsql STABLE;

-- Is the promotion valid for this product, branch and moment?
CREATE OR REPLACE FUNCTION fn_promotion_applies(
    p_promotion_id UUID, p_product_id UUID, p_branch_id UUID, p_at TIMESTAMPTZ DEFAULT NOW())
RETURNS BOOLEAN AS $$
    SELECT EXISTS (
        SELECT 1
        FROM promotions p
        JOIN promotion_products pp ON pp.promotion_id = p.id
                                  AND pp.product_id = p_product_id AND pp.deleted_at IS NULL
        WHERE p.id = p_promotion_id
          AND p.deleted_at IS NULL AND p.is_enabled
          AND p_at >= p.starts_at AND p_at < p.ends_at
          AND (NOT EXISTS (SELECT 1 FROM promotion_branches b
                            WHERE b.promotion_id = p.id AND b.deleted_at IS NULL)
               OR EXISTS (SELECT 1 FROM promotion_branches b
                           WHERE b.promotion_id = p.id AND b.branch_id = p_branch_id AND b.deleted_at IS NULL))
    );
$$ LANGUAGE sql STABLE;

-- What is on offer in a branch right now (one row per promotion and product)
CREATE OR REPLACE FUNCTION fn_active_promotions(p_branch_id UUID, p_at TIMESTAMPTZ DEFAULT NOW())
RETURNS TABLE (promotion_id UUID, product_id UUID, name VARCHAR, kind VARCHAR,
               percent NUMERIC, amount NUMERIC, buy_quantity INTEGER, get_quantity INTEGER,
               ends_at TIMESTAMPTZ) AS $$
    SELECT p.id, pp.product_id, p.name, p.kind, p.percent, p.amount, p.buy_quantity, p.get_quantity, p.ends_at
    FROM promotions p
    JOIN promotion_products pp ON pp.promotion_id = p.id AND pp.deleted_at IS NULL
    WHERE fn_promotion_applies(p.id, pp.product_id, p_branch_id, p_at);
$$ LANGUAGE sql STABLE;

