-- A payment never exceeds what is still owed, its parent must be active, and a cash payment must be the
-- matching money-out movement (same amount, same register, a register of the parent's branch)
CREATE OR REPLACE FUNCTION fn_outgoing_payments_before_insert()
RETURNS TRIGGER AS $$
DECLARE
    v_branch UUID;
    v_total  NUMERIC(12,2);
    v_paid   NUMERIC(12,2);
BEGIN
    IF NEW.expense_id IS NOT NULL THEN
        SELECT branch_id, amount INTO v_branch, v_total FROM expenses WHERE id = NEW.expense_id AND deleted_at IS NULL FOR UPDATE;
    ELSE
        SELECT branch_id, total INTO v_branch, v_total FROM purchases WHERE id = NEW.purchase_id AND deleted_at IS NULL FOR UPDATE;
    END IF;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'The expense or purchase does not exist or was voided';
    END IF;

    SELECT COALESCE(SUM(amount), 0) INTO v_paid FROM outgoing_payments
     WHERE expense_id IS NOT DISTINCT FROM NEW.expense_id AND purchase_id IS NOT DISTINCT FROM NEW.purchase_id;
    IF v_paid + NEW.amount > v_total THEN
        RAISE EXCEPTION 'Payment exceeds what is owed (total %, already paid %)', v_total, v_paid;
    END IF;

    IF NEW.source = 'CASH' THEN
        PERFORM 1 FROM cash_register_movements m JOIN cash_registers r ON r.id = m.cash_register_id
         WHERE m.id = NEW.cash_movement_id AND m.cash_register_id = NEW.cash_register_id
           AND m.amount = -NEW.amount AND r.branch_id = v_branch;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'A cash payment needs its money-out movement in a register of the same branch';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_outgoing_payments_before_insert
