CREATE OR REPLACE FUNCTION fn_sale_items_apply_promotion()
RETURNS TRIGGER AS $$
DECLARE
    v_branch   UUID;
    v_sold_at  TIMESTAMPTZ;
    v_discount NUMERIC(12,2);
BEGIN
    SELECT branch_id, sold_at INTO v_branch, v_sold_at FROM sales WHERE id = NEW.sale_id;

    IF NOT fn_promotion_applies(NEW.promotion_id, NEW.product_id, v_branch, v_sold_at) THEN
        RAISE EXCEPTION 'Promotion % does not apply to product % in this branch at the time of the sale',
            NEW.promotion_id, NEW.product_id;
    END IF;

    v_discount := fn_promotion_discount(NEW.promotion_id, NEW.quantity, NEW.unit_price);

    IF NEW.discount <> 0 AND NEW.discount <> v_discount THEN
        RAISE EXCEPTION 'The discount of a promotion line is calculated by the database (%), not %', v_discount, NEW.discount;
    END IF;

    NEW.discount := v_discount;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

