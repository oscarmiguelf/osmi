-- ---------------------------------------------------------------------
-- customer_credit_movements (append-only ledger of the customer's account)
--   amount is SIGNED from the customer's debt point of view:
--     charge  > 0  debt goes up   (credit portion of a sale)
--     payment < 0  debt goes down (abono)
--     return  < 0  debt goes down (credit portion cancelled by a return)
--   Rows are created only by the triggers of sale payments and returns.
-- ---------------------------------------------------------------------
CREATE TABLE customer_credit_movements (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id    UUID          NOT NULL REFERENCES customers (id),
    sale_id        UUID          NOT NULL REFERENCES sales (id),
    movement_type  VARCHAR(10)   NOT NULL,
    amount         NUMERIC(12,2) NOT NULL,
    balance_before NUMERIC(12,2) NOT NULL,                -- set by trigger
    balance_after  NUMERIC(12,2) NOT NULL,                -- set by trigger

    created_by     UUID          NOT NULL REFERENCES users (id),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_credit_movements_type   CHECK (movement_type IN ('charge', 'payment', 'return')),
    CONSTRAINT chk_credit_movements_amount CHECK (
        (movement_type = 'charge' AND amount > 0) OR (movement_type <> 'charge' AND amount < 0))
);

CREATE INDEX idx_credit_movements_customer ON customer_credit_movements (customer_id, created_at DESC);
CREATE INDEX idx_credit_movements_sale     ON customer_credit_movements (sale_id);

CREATE TRIGGER trg_credit_movements_append_only
    BEFORE UPDATE OR DELETE ON customer_credit_movements
    FOR EACH ROW EXECUTE FUNCTION prevent_modification();

CREATE OR REPLACE FUNCTION fn_customer_credit_movement_apply()
RETURNS TRIGGER AS $$
DECLARE
    v_before NUMERIC(12,2);
    v_after  NUMERIC(12,2);
    v_limit  NUMERIC(12,2);
BEGIN
    IF COALESCE(current_setting('app.customer_credit', TRUE), 'off') <> 'on' THEN
        RAISE EXCEPTION 'Customer credit movements are created automatically by sale payments and returns';
    END IF;

    -- make sure the balance row exists, then lock it (concurrent movements are serialized)
    INSERT INTO customer_credit_balances (customer_id) VALUES (NEW.customer_id)
    ON CONFLICT (customer_id) DO NOTHING;

    SELECT balance INTO v_before
      FROM customer_credit_balances WHERE customer_id = NEW.customer_id FOR UPDATE;

    v_after := v_before + NEW.amount;

    IF NEW.movement_type = 'charge' THEN
        SELECT credit_limit INTO v_limit FROM customers WHERE id = NEW.customer_id;
        IF v_after > v_limit THEN
            RAISE EXCEPTION 'Credit limit exceeded for customer %: limit %, debt would be %',
                NEW.customer_id, v_limit, v_after;
        END IF;
    END IF;

    IF v_after < 0 THEN
        RAISE EXCEPTION 'The customer % does not owe that much (debt %, movement %)',
            NEW.customer_id, v_before, NEW.amount;
    END IF;

    UPDATE customer_credit_balances
       SET balance = v_after, updated_at = NOW()
     WHERE customer_id = NEW.customer_id;

    NEW.balance_before := v_before;
    NEW.balance_after  := v_after;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_credit_movements_apply
    BEFORE INSERT ON customer_credit_movements
    FOR EACH ROW EXECUTE FUNCTION fn_customer_credit_movement_apply();

-- Helper used by the payment and return triggers
CREATE OR REPLACE FUNCTION fn_customer_credit_move(
    p_customer_id UUID, p_sale_id UUID, p_type TEXT, p_amount NUMERIC, p_user_id UUID)
RETURNS VOID AS $$
BEGIN
