-- #####################################################################
-- FILE: returns_schema.sql
-- #####################################################################
-- =====================================================================
-- Returns module: partial sale returns with refund
-- Target: PostgreSQL 13+
-- Depends on:
--   auth_schema.sql      -> users
--   branches_schema.sql  -> fn_user_in_branch(), fn_next_folio()
--   inventory_schema.sql -> inventory_movements, prevent_modification()
--   cash_schema.sql      -> payment_methods, cash registers / sessions / movements
--   sales_schema.sql     -> sales, sale_items, fn_set_sale_status(), fn_sales_audit()
--   payments_schema.sql  -> fn_sale_credit_outstanding(), fn_customer_credit_move()
--
-- How it works (one return = ONE transaction with header, items and refunds):
--   * sale_returns         header, with its own folio (e.g. SUC1-R000045)
--   * sale_return_items    which sale items and how many units come back
--   * sale_return_refunds  how the money goes back (one row per payment method)
--
-- Automatic effects:
--   * STOCK comes back in the sale's branch. A kit gives back its components in the
--     same proportion they were taken out. Services move nothing.
--   * The refund amount of each item is calculated by the database: the net value of
--     the line (after the sale-level discount) pro-rated by the units returned.
--     Returning the last units never leaves cents behind.
--   * Refund with a real method -> a 'Return' cash movement (money OUT) in the register
--     where the return is processed. Refund with Credit -> cancels customer debt.
--   * When every unit of every item has been returned the sale becomes RETURNED.
--   * A RETURNED sale can't keep credit owed: the credit portion must be refunded.
--   * Everything is append-only and audited.
-- =====================================================================


-- ---------------------------------------------------------------------
-- sale_returns (header)
-- ---------------------------------------------------------------------
CREATE TABLE sale_returns (
    id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    folio            VARCHAR(30)   NOT NULL,                 -- set by trigger
    sale_id          UUID          NOT NULL REFERENCES sales (id),
    branch_id        UUID          NOT NULL REFERENCES branches (id),   -- set by trigger (= the sale's)
    cash_register_id UUID          NOT NULL,                -- register where the return is processed
    refund_total     NUMERIC(12,2) NOT NULL,                -- = sum of items = sum of refunds
    reason           TEXT,

    created_by       UUID          NOT NULL REFERENCES users (id),
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_sale_returns_register
        FOREIGN KEY (cash_register_id, branch_id) REFERENCES cash_registers (id, branch_id),
    CONSTRAINT chk_sale_returns_total CHECK (refund_total >= 0)
);

CREATE UNIQUE INDEX uq_sale_returns_folio ON sale_returns (folio);
CREATE INDEX idx_sale_returns_sale   ON sale_returns (sale_id, created_at);
CREATE INDEX idx_sale_returns_branch ON sale_returns (branch_id, created_at DESC);
CREATE INDEX idx_sale_returns_user   ON sale_returns (created_by, created_at DESC);

