-- =====================================================================
-- Taxes module: tax rates, tax per product, tax breakdown of sales
-- Target: PostgreSQL 13+
-- Depends on: auth, products, sales (and the earlier modules)
--
-- Rules:
--   * PRICES INCLUDE TAX (the price on the shelf is the price paid, as in retail).
--     The tax is the part of the amount that is tax:
--         tax = ROUND(net_amount * rate / (1 + rate), 2)
--   * Every product has a tax rate (default: the rate marked is_default).
--   * Each sale item keeps a SNAPSHOT of the rate and the tax amount at the moment of
--     the sale, so changing a rate later never alters old sales.
--   * sale_items.tax_amount = tax of the line (after the line discount).
--   * sales.tax_total      = tax contained in the sale total, i.e. the sum of the lines'
--     tax scaled by the sale-level discount:
--         tax_total = ROUND(SUM(tax_amount) * total / subtotal, 2)    (0 if subtotal = 0)
--     The backend sends tax_total in the sale header; the database validates it at
--     COMMIT and, if it doesn't match, the error message shows the expected value.
--   * Quotes and purchases do not carry tax detail.
-- =====================================================================


-- ---------------------------------------------------------------------
-- tax_rates
--   rate is a fraction: 0.1600 = 16 %
-- ---------------------------------------------------------------------
CREATE TABLE tax_rates (
    id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name       VARCHAR(100)  NOT NULL,
    rate       NUMERIC(5,4)  NOT NULL,
    is_default BOOLEAN       NOT NULL DEFAULT FALSE,

    created_by UUID          REFERENCES users (id),      -- NULL = system / seed
    updated_by UUID          REFERENCES users (id),
    created_at TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ,
    deleted_by UUID          REFERENCES users (id),

    CONSTRAINT chk_tax_rates_name    CHECK (BTRIM(name) <> ''),
    CONSTRAINT chk_tax_rates_rate    CHECK (rate >= 0 AND rate < 1),
    CONSTRAINT chk_tax_rates_deleted CHECK ((deleted_at IS NULL) = (deleted_by IS NULL))
);

CREATE UNIQUE INDEX uq_tax_rates_name    ON tax_rates (LOWER(name)) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX uq_tax_rates_default ON tax_rates ((TRUE))      WHERE is_default AND deleted_at IS NULL;

