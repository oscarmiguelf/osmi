-- ---------------------------------------------------------------------
-- Totals check, deferred to COMMIT (so header and items can be inserted
-- in any order inside one transaction):
--   * a sale must have at least one item
--   * sales.subtotal must equal SUM(sale_items.line_total)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_sale_check_totals()
RETURNS TRIGGER AS $$
DECLARE
    v_sale_id  UUID;
    v_count    INTEGER;
    v_sum      NUMERIC(12,2);
    v_subtotal NUMERIC(12,2);
BEGIN
    v_sale_id := CASE TG_TABLE_NAME WHEN 'sales' THEN NEW.id ELSE (TO_JSONB(NEW) ->> 'sale_id')::UUID END;  -- NEW.sale_id would fail on the header table

    SELECT subtotal INTO v_subtotal FROM sales WHERE id = v_sale_id;
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    SELECT COUNT(*), COALESCE(SUM(line_total), 0)
      INTO v_count, v_sum
      FROM sale_items WHERE sale_id = v_sale_id;

    IF v_count = 0 THEN
        RAISE EXCEPTION 'Sale % must have at least one item', v_sale_id;
    END IF;

    IF v_sum <> v_subtotal THEN
        RAISE EXCEPTION 'Sale %: subtotal % does not match the sum of its items %', v_sale_id, v_subtotal, v_sum;
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_sales_check_totals
    AFTER INSERT ON sales
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_sale_check_totals();

CREATE CONSTRAINT TRIGGER trg_sale_items_check_totals
    AFTER INSERT ON sale_items
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_sale_check_totals();

