CREATE OR REPLACE FUNCTION fn_sale_returns_before_insert()
RETURNS TRIGGER AS $$
DECLARE
    v_branch UUID;
    v_status TEXT;
BEGIN
    SELECT s.branch_id, st.name INTO v_branch, v_status
      FROM sales s JOIN sale_statuses st ON st.id = s.status_id
     WHERE s.id = NEW.sale_id AND s.deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Sale % does not exist or is deleted', NEW.sale_id;
