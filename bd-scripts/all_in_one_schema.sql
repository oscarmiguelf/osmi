    IF v_status = 'RETURNED' THEN
        RAISE EXCEPTION 'The sale is already fully RETURNED';
    END IF;

    NEW.branch_id := v_branch;

    IF NOT fn_user_in_branch(NEW.created_by, v_branch) THEN
