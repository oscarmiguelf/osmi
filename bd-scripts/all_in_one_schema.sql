    -- The balance of an open appointment's sale (made when it's booked, paid with deposits) doesn't need a credit limit
    IF NEW.movement_type = 'charge'
       AND NOT EXISTS (SELECT 1 FROM appointments WHERE sale_id = NEW.sale_id AND status IN ('SCHEDULED', 'CONFIRMED')) THEN
        SELECT credit_limit INTO v_limit FROM customers WHERE id = NEW.customer_id;
        IF v_after > v_limit THEN
            RAISE EXCEPTION 'Credit limit exceeded for customer %: limit %, debt would be %',
                NEW.customer_id, v_limit, v_after;
        END IF;
    END IF;

    IF v_after < 0 THEN
        RAISE EXCEPTION 'The customer % does not owe that much (debt %, movement %)',
            NEW.customer_id, v_before, NEW.amount;
    END IF;

    UPDATE customer_credit_balances
       SET balance = v_after, updated_at = NOW()
     WHERE customer_id = NEW.customer_id;

    NEW.balance_before := v_before;
    NEW.balance_after  := v_after;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- =====================================================================
-- A cash cut closes the turn: the register is released, what isn't cash goes back to 0 (it was counted and handed
-- in), the cash stays at what was really counted, and part of it can be taken out (the cut withdrawal, with a reason).
--   'Cut' movements: the counted difference of the cash and the reset of the other methods (made by the API with the cut)
-- =====================================================================
INSERT INTO cash_movement_types (name)
SELECT 'Cut' WHERE NOT EXISTS (SELECT 1 FROM cash_movement_types WHERE LOWER(name) = 'cut' AND deleted_at IS NULL);
ALTER TABLE cash_cuts ADD COLUMN IF NOT EXISTS withdrawn NUMERIC(12,2) NOT NULL DEFAULT 0;
ALTER TABLE cash_cuts ADD COLUMN IF NOT EXISTS withdrawal_reason VARCHAR(200);
ALTER TABLE cash_cuts DROP CONSTRAINT IF EXISTS chk_cash_cuts_withdrawn;
ALTER TABLE cash_cuts ADD CONSTRAINT chk_cash_cuts_withdrawn CHECK (withdrawn >= 0);

-- =====================================================================
-- appointments.own: the person sees only the appointments assigned to them or that they booked (a doctor, a
-- therapist). Without it, everything of the branch (front desk, managers). Not granted to anyone by default.
-- =====================================================================
INSERT INTO permissions (module_id, code, name)
SELECT m.id, 'own', 'Only their own appointments' FROM modules m WHERE m.code = 'appointments'
ON CONFLICT (module_id, code) DO NOTHING;

-- =====================================================================
-- payment_methods.is_cash: THE cash method (the one that stays in the drawer, takes change, pays expenses from the
-- register). Marked by a flag, not by its name: renaming "Cash" (or translating it) must not break anything.
-- At most one, and it can't be the credit method.
-- =====================================================================
ALTER TABLE payment_methods ADD COLUMN IF NOT EXISTS is_cash BOOLEAN NOT NULL DEFAULT FALSE;
UPDATE payment_methods SET is_cash = TRUE
 WHERE description = 'Cash' AND NOT is_credit AND deleted_at IS NULL
   AND NOT EXISTS (SELECT 1 FROM payment_methods WHERE is_cash AND deleted_at IS NULL);
ALTER TABLE payment_methods DROP CONSTRAINT IF EXISTS chk_payment_methods_cash_not_credit;
ALTER TABLE payment_methods ADD CONSTRAINT chk_payment_methods_cash_not_credit CHECK (NOT (is_cash AND is_credit));
CREATE UNIQUE INDEX IF NOT EXISTS uq_payment_methods_cash ON payment_methods (is_cash) WHERE is_cash AND deleted_at IS NULL;
