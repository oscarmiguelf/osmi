-- ---------------------------------------------------------------------
-- sales: validations on UPDATE
--   * financial fields, seller, sale date, branch and cash register can't change
--   * allowed status transitions:
--       PENDING -> PAID | RETURNED      PAID -> RETURNED      RETURNED -> (none)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_sales_before_update()
RETURNS TRIGGER AS $$
DECLARE
    v_old TEXT;
    v_new TEXT;
BEGIN
    IF NEW.subtotal   IS DISTINCT FROM OLD.subtotal
    OR NEW.discount   IS DISTINCT FROM OLD.discount
    OR NEW.total      IS DISTINCT FROM OLD.total
    OR NEW.sold_at    IS DISTINCT FROM OLD.sold_at
    OR NEW.branch_id  IS DISTINCT FROM OLD.branch_id
    OR NEW.cash_register_id IS DISTINCT FROM OLD.cash_register_id
    OR NEW.created_by IS DISTINCT FROM OLD.created_by THEN
        RAISE EXCEPTION 'subtotal, discount, total, sold_at, branch, cash register and seller cannot be changed. Register a return to undo a sale';
    END IF;

    -- A sale can only be voided (soft-deleted) after it was RETURNED (stock is back in)
    IF OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL THEN
        SELECT name INTO v_new FROM sale_statuses WHERE id = NEW.status_id;
        IF v_new IS DISTINCT FROM 'RETURNED' THEN
            RAISE EXCEPTION 'Return the sale (status RETURNED) before deleting it, so its stock goes back in';
        END IF;
    END IF;

    IF NEW.status_id IS DISTINCT FROM OLD.status_id THEN
        IF COALESCE(current_setting('app.sale_status', TRUE), 'off') <> 'on' THEN
            RAISE EXCEPTION 'The sale status is managed by the system (payments and returns); it cannot be changed by hand';
        END IF;

        SELECT name INTO v_old FROM sale_statuses WHERE id = OLD.status_id;
        SELECT name INTO v_new FROM sale_statuses WHERE id = NEW.status_id;

        IF NOT ((v_old = 'PENDING' AND v_new IN ('PAID', 'RETURNED'))
             OR (v_old = 'PAID'    AND v_new = 'RETURNED')) THEN
            RAISE EXCEPTION 'Invalid sale status change: % -> %', v_old, v_new;
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_sales_before_update
    BEFORE UPDATE ON sales
    FOR EACH ROW EXECUTE FUNCTION fn_sales_before_update();

