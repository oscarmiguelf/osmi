    INSERT INTO purchases_audit (entity_type, entity_id, purchase_id, action, changed_by, changed_fields, old_data, new_data)
    VALUES (v_entity, NEW.id, v_purchase_id, v_action, v_user_id, v_changed, v_old, v_new);

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

