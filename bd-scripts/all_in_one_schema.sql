-- ---------------------------------------------------------------------
-- Apply the movement to product_stock (runs BEFORE the row is inserted)
--   1) the product must exist and not be deleted
--   2) locks the stock row, so concurrent movements are serialized
--   3) rejects the movement if it would leave negative stock
--   4) updates (or creates) product_stock, attributed to the movement's user
--      -> the stock change is audited in product_audit with that user
--   5) stores stock_before / stock_after in the movement
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_inventory_movement_apply()
RETURNS TRIGGER AS $$
DECLARE
    v_before NUMERIC(14,3);
    v_after  NUMERIC(14,3);
BEGIN
    PERFORM 1 FROM branches WHERE id = NEW.branch_id AND deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Branch % does not exist or is deleted', NEW.branch_id;
    END IF;

    IF NOT fn_user_in_branch(NEW.created_by, NEW.branch_id) THEN
        RAISE EXCEPTION 'User % does not belong to branch %', NEW.created_by, NEW.branch_id;
    END IF;

    PERFORM 1 FROM products WHERE id = NEW.product_id AND deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Product % does not exist or is deleted', NEW.product_id;
    END IF;

    PERFORM 1 FROM inventory_movement_types WHERE id = NEW.movement_type_id AND deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Movement type % does not exist or is deleted', NEW.movement_type_id;
    END IF;

    -- Allow product_stock.current_stock to change inside this transaction step
    PERFORM set_config('app.inventory_movement', 'on', TRUE);

    SELECT current_stock
      INTO v_before
      FROM product_stock
     WHERE product_id = NEW.product_id AND branch_id = NEW.branch_id AND deleted_at IS NULL
       FOR UPDATE;

    IF NOT FOUND THEN
        v_before := 0;
        v_after  := NEW.quantity;
        IF v_after < 0 THEN
            RAISE EXCEPTION 'Insufficient stock for product % in branch %: available 0, requested %', NEW.product_id, NEW.branch_id, -NEW.quantity;
        END IF;

        INSERT INTO product_stock (product_id, branch_id, current_stock, created_by, updated_by)
        VALUES (NEW.product_id, NEW.branch_id, v_after, NEW.created_by, NEW.created_by);
    ELSE
        v_after := v_before + NEW.quantity;
        IF v_after < 0 THEN
            RAISE EXCEPTION 'Insufficient stock for product % in branch %: available %, requested %', NEW.product_id, NEW.branch_id, v_before, -NEW.quantity;
        END IF;

        UPDATE product_stock
           SET current_stock = v_after,
               updated_by    = NEW.created_by
         WHERE product_id = NEW.product_id AND branch_id = NEW.branch_id AND deleted_at IS NULL;
    END IF;

    PERFORM set_config('app.inventory_movement', 'off', TRUE);

    NEW.stock_before := v_before;
    NEW.stock_after  := v_after;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_inv_movements_apply
    BEFORE INSERT ON inventory_movements
    FOR EACH ROW EXECUTE FUNCTION fn_inventory_movement_apply();

