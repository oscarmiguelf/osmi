CREATE INDEX idx_user_branches_branch ON user_branches (branch_id) WHERE deleted_at IS NULL;

-- ---------------------------------------------------------------------
-- Triggers: updated_at + block physical DELETE
-- ---------------------------------------------------------------------
DO $$
DECLARE
    t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['branches', 'user_branches']
    LOOP
        EXECUTE FORMAT(
            'CREATE TRIGGER trg_%1$s_updated_at BEFORE UPDATE ON %1$I
             FOR EACH ROW EXECUTE FUNCTION set_updated_at()', t);
        EXECUTE FORMAT(
            'CREATE TRIGGER trg_%1$s_no_hard_delete BEFORE DELETE ON %1$I
             FOR EACH ROW EXECUTE FUNCTION prevent_hard_delete()', t);
    END LOOP;
END $$;

-- ---------------------------------------------------------------------
-- Helper used by other modules: does this user belong to this branch?
--   True only if the membership is active, the branch is not deleted and
--   the user is active and not deleted.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_user_in_branch(p_user_id UUID, p_branch_id UUID)
RETURNS BOOLEAN AS $$
    SELECT EXISTS (
        SELECT 1
        FROM user_branches ub
        JOIN branches b ON b.id = ub.branch_id AND b.deleted_at IS NULL
        JOIN users u    ON u.id = ub.user_id   AND u.deleted_at IS NULL AND u.is_active
        WHERE ub.user_id = p_user_id
          AND ub.branch_id = p_branch_id
