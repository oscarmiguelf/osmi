-- Tax the database expects for a sale, from its items (use it to verify or to build the header)
CREATE OR REPLACE FUNCTION fn_sale_expected_tax(p_sale_id UUID)
RETURNS NUMERIC AS $$
DECLARE
    v_subtotal NUMERIC(12,2);
    v_total    NUMERIC(12,2);
    v_tax      NUMERIC(12,2);
BEGIN
    SELECT subtotal, total INTO v_subtotal, v_total FROM sales WHERE id = p_sale_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Sale % does not exist', p_sale_id;
    END IF;
    IF v_subtotal = 0 THEN
        RETURN 0;
    END IF;
    SELECT COALESCE(SUM(tax_amount), 0) INTO v_tax FROM sale_items WHERE sale_id = p_sale_id;
    RETURN ROUND(v_tax * v_total / v_subtotal, 2);
END;
$$ LANGUAGE plpgsql STABLE;

CREATE OR REPLACE FUNCTION fn_sale_check_tax()
RETURNS TRIGGER AS $$
DECLARE
    v_sale_id  UUID;
    v_tax      NUMERIC(12,2);
    v_expected NUMERIC(12,2);
BEGIN
    v_sale_id := CASE TG_TABLE_NAME WHEN 'sales' THEN NEW.id ELSE (TO_JSONB(NEW) ->> 'sale_id')::UUID END;  -- NEW.sale_id would fail on the header table

    SELECT tax_total INTO v_tax FROM sales WHERE id = v_sale_id;
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    v_expected := fn_sale_expected_tax(v_sale_id);
    IF v_tax <> v_expected THEN
        RAISE EXCEPTION 'Sale %: tax_total % does not match the tax of its items %', v_sale_id, v_tax, v_expected;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

