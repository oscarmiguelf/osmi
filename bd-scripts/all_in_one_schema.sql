-- =====================================================================
-- Appointments (citas): a calendar of appointments with customers, per branch
-- Depends on: auth (users, set_updated_at, prevent_modification), branches (fn_user_in_branch),
--             customers
--
-- How it works:
--   * An appointment belongs to ONE branch and ONE customer, has a reason (title), a start and an
--     end (UTC), and optionally the user who attends it (assigned_to).
--   * Status: SCHEDULED -> CONFIRMED -> COMPLETED, or -> CANCELLED / NO_SHOW at any open point.
--     COMPLETED, CANCELLED and NO_SHOW are final: the appointment can't change any more.
--   * Rescheduling = changing starts_at / ends_at of an open appointment. It's counted
--     (reschedule_count) and recorded in appointment_history with the old and new times and the
--     reason. A CONFIRMED appointment that is rescheduled goes back to SCHEDULED (confirm it again).
--   * Appointments are never deleted: they are cancelled (with a reason) and stay in the history.
--   * The same person can't have two open appointments at the same time (assigned_to overlap).
--   * appointment_notes: follow-up notes (append-only, who and when).
--   * appointment_history: every creation, reschedule and status change (filled by triggers).
-- =====================================================================

CREATE TABLE appointments (
    id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    branch_id        UUID         NOT NULL REFERENCES branches (id),
    customer_id      UUID         NOT NULL REFERENCES customers (id),
    assigned_to      UUID         REFERENCES users (id),            -- who attends it (optional)
    title            VARCHAR(200) NOT NULL,                         -- reason of the appointment
    notes            TEXT,                                          -- general notes (editable while open)
    starts_at        TIMESTAMPTZ  NOT NULL,
    ends_at          TIMESTAMPTZ  NOT NULL,
    status           VARCHAR(12)  NOT NULL DEFAULT 'SCHEDULED',
    cancel_reason    VARCHAR(500),
    reschedule_count INTEGER      NOT NULL DEFAULT 0,               -- set by trigger

    created_by       UUID         NOT NULL REFERENCES users (id),
    updated_by       UUID         NOT NULL REFERENCES users (id),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_appointments_title  CHECK (BTRIM(title) <> ''),
    CONSTRAINT chk_appointments_range  CHECK (ends_at > starts_at),
    CONSTRAINT chk_appointments_status CHECK (status IN ('SCHEDULED', 'CONFIRMED', 'COMPLETED', 'CANCELLED', 'NO_SHOW')),
    CONSTRAINT chk_appointments_cancel CHECK (cancel_reason IS NULL OR status = 'CANCELLED')
);

