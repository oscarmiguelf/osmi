-- ---------------------------------------------------------------------
-- Access helper: what can this user do in this calendar?
--   Returns 'owner' | 'edit' | 'view' | NULL (no access, or calendar deleted)
--   Use it in the backend before every calendar/event operation:
--     view  -> can read          edit  -> can also create/modify events
--     owner -> everything, including sharing and deleting the calendar
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_calendar_access_level(p_user_id UUID, p_calendar_id UUID)
RETURNS TEXT AS $$
    SELECT CASE WHEN c.owner_id = p_user_id THEN 'owner' ELSE m.access_level END
    FROM calendars c
    LEFT JOIN calendar_members m
           ON m.calendar_id = c.id
          AND m.user_id = p_user_id
          AND m.deleted_at IS NULL
    WHERE c.id = p_calendar_id
      AND c.deleted_at IS NULL;
$$ LANGUAGE sql STABLE;


