-- ---------------------------------------------------------------------
-- Audit trigger
--   INSERT  -> user = NEW.created_by
--   UPDATE  -> user = NEW.updated_by   (app MUST set it on every update)
--   DELETE  -> logical: deleted_at goes NULL -> value, user = NEW.deleted_by
--   RESTORE -> logical: deleted_at goes value -> NULL, user = NEW.updated_by
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_customers_audit()
RETURNS TRIGGER AS $$
DECLARE
    v_action  TEXT;
    v_user_id UUID;
    v_changed TEXT[];
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO customers_audit (customer_id, action, changed_by, new_data)
        VALUES (NEW.id, 'INSERT', NEW.created_by, TO_JSONB(NEW));
        RETURN NEW;
    END IF;

    -- UPDATE: skip no-op updates
    IF TO_JSONB(NEW) - 'updated_at' - 'updated_by'
       = TO_JSONB(OLD) - 'updated_at' - 'updated_by' THEN
        RETURN NEW;
    END IF;

    IF OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL THEN
        v_action  := 'DELETE';
        v_user_id := NEW.deleted_by;
    ELSIF OLD.deleted_at IS NOT NULL AND NEW.deleted_at IS NULL THEN
        v_action  := 'RESTORE';
        v_user_id := NEW.updated_by;
    ELSE
        v_action  := 'UPDATE';
        v_user_id := NEW.updated_by;
    END IF;

    SELECT ARRAY_AGG(n.key ORDER BY n.key)
      INTO v_changed
      FROM JSONB_EACH(TO_JSONB(NEW)) n
      JOIN JSONB_EACH(TO_JSONB(OLD)) o USING (key)
     WHERE n.value IS DISTINCT FROM o.value
       AND n.key <> 'updated_at';

    INSERT INTO customers_audit (customer_id, action, changed_by, changed_fields, old_data, new_data)
    VALUES (NEW.id, v_action, v_user_id, v_changed, TO_JSONB(OLD), TO_JSONB(NEW));

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_customers_audit
    AFTER INSERT OR UPDATE ON customers
