-- ---------------------------------------------------------------------
-- document_sequences: one counter per branch and document type, for readable folios
--   sale        -> SUC1-000123
--   sale_return -> SUC1-R000045
--   quote       -> SUC1-Q000007
--   transfer    -> SUC1-T000003
-- ---------------------------------------------------------------------
CREATE TABLE document_sequences (
    branch_id     UUID        NOT NULL REFERENCES branches (id),
    document_type VARCHAR(20) NOT NULL,
    last_number   BIGINT      NOT NULL DEFAULT 0,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (branch_id, document_type),
    CONSTRAINT chk_document_sequences_type   CHECK (document_type IN ('sale', 'sale_return', 'quote', 'transfer', 'stocktake')),
    CONSTRAINT chk_document_sequences_number CHECK (last_number >= 0)
);

-- Next folio. The UPDATE locks the counter row until the transaction ends, so two
-- concurrent documents of the same branch can never get the same number, and a
-- rolled-back transaction does not burn a number (no gaps).
CREATE OR REPLACE FUNCTION fn_next_folio(p_branch_id UUID, p_document_type TEXT)
RETURNS TEXT AS $$
DECLARE
    v_code   TEXT;
    v_prefix TEXT;
    v_number BIGINT;
BEGIN
    SELECT code INTO v_code FROM branches WHERE id = p_branch_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Branch % does not exist', p_branch_id;
    END IF;

    v_prefix := CASE p_document_type
                    WHEN 'sale'        THEN ''
                    WHEN 'sale_return' THEN 'R'
                    WHEN 'quote'       THEN 'Q'
                    WHEN 'transfer'    THEN 'T'
                    WHEN 'stocktake'   THEN 'C'
                END;
    IF v_prefix IS NULL THEN
        RAISE EXCEPTION 'Unknown document type %', p_document_type;
    END IF;

    INSERT INTO document_sequences (branch_id, document_type, last_number)
    VALUES (p_branch_id, p_document_type, 1)
    ON CONFLICT (branch_id, document_type)
    DO UPDATE SET last_number = document_sequences.last_number + 1, updated_at = NOW()
    RETURNING last_number INTO v_number;

    RETURN v_code || '-' || v_prefix || LPAD(v_number::TEXT, 6, '0');
END;
$$ LANGUAGE plpgsql;

