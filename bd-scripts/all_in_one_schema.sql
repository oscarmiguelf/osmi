-- FILE: stocktakes_schema.sql
-- #####################################################################
-- =====================================================================
-- Stocktakes module: physical inventory count per branch
-- Target: PostgreSQL 13+
-- Depends on:
--   auth_schema.sql      -> users, set_updated_at(), prevent_hard_delete()
--   branches_schema.sql  -> branches, fn_user_in_branch(), fn_next_folio()
--   products_schema.sql  -> products, product_types, product_stock
--   inventory_schema.sql -> inventory_movements, inventory_movement_types
--
-- How it works:
--   * A stocktake belongs to ONE branch and has a folio (SUC1-C000001). A branch can have
--     only one OPEN stocktake at a time.
--   * While OPEN, users record what they physically counted: one row per product
--     (stocktake_items). system_quantity is the stock the system showed when it was counted;
--     difference = counted - system. A count can be corrected while OPEN, and a wrongly
--     added product can be removed (soft delete).
--   * COMPLETING the stocktake (OPEN -> COMPLETED) leaves the stock of every counted product
--     EXACTLY equal to what was counted: for each item the database registers an
--     'Adjustment' inventory movement for (counted - stock at that moment). The applied
--     adjustment is stored in the item. Products not counted are not touched.
--     => Count while the branch is not selling; sales made between counting a product and
--        completing the stocktake are overwritten by the counted value.
--   * CANCELLING (OPEN -> CANCELLED) changes no stock.
--   * Only products that track stock can be counted (not services, not kits).
--   * Completed and cancelled stocktakes can't be modified. Everything is audited.
-- =====================================================================


-- ---------------------------------------------------------------------
-- stocktakes
-- ---------------------------------------------------------------------
CREATE TABLE stocktakes (
    id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    folio      VARCHAR(30)  NOT NULL,                    -- set by trigger
    branch_id  UUID         NOT NULL REFERENCES branches (id),
    status     VARCHAR(10)  NOT NULL DEFAULT 'OPEN',
    notes      TEXT,
    closed_at  TIMESTAMPTZ,                              -- completed or cancelled at (set by trigger)
    closed_by  UUID         REFERENCES users (id),       -- set by trigger (= updated_by of the closing update)

    created_by UUID         NOT NULL REFERENCES users (id),
    updated_by UUID         NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_stocktakes_status CHECK (status IN ('OPEN', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT chk_stocktakes_closed CHECK ((status = 'OPEN') = (closed_at IS NULL AND closed_by IS NULL))
);

CREATE UNIQUE INDEX uq_stocktakes_folio       ON stocktakes (folio);
CREATE UNIQUE INDEX uq_stocktakes_branch_open ON stocktakes (branch_id) WHERE status = 'OPEN';
CREATE INDEX idx_stocktakes_branch            ON stocktakes (branch_id, created_at DESC);

CREATE TRIGGER trg_stocktakes_updated_at
    BEFORE UPDATE ON stocktakes FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_stocktakes_no_delete
    BEFORE DELETE ON stocktakes FOR EACH ROW EXECUTE FUNCTION prevent_modification();

-- ---------------------------------------------------------------------
-- stocktake_items
-- ---------------------------------------------------------------------
CREATE TABLE stocktake_items (
    id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    stocktake_id       UUID          NOT NULL REFERENCES stocktakes (id),
    product_id         UUID          NOT NULL REFERENCES products (id),
    system_quantity    NUMERIC(14,3) NOT NULL,           -- stock shown by the system when counted (trigger)
    counted_quantity   NUMERIC(14,3) NOT NULL,
    difference         NUMERIC(14,3) GENERATED ALWAYS AS (counted_quantity - system_quantity) STORED,
    applied_adjustment NUMERIC(14,3),                    -- set when the stocktake is completed
    notes              VARCHAR(500),

    created_by         UUID          NOT NULL REFERENCES users (id),   -- who counted it
    updated_by         UUID          NOT NULL REFERENCES users (id),   -- defaults to created_by on insert
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    deleted_at         TIMESTAMPTZ,
    deleted_by         UUID          REFERENCES users (id),

    CONSTRAINT chk_stocktake_items_counted CHECK (counted_quantity >= 0),
    CONSTRAINT chk_stocktake_items_deleted CHECK ((deleted_at IS NULL) = (deleted_by IS NULL))
